const assert=require('node:assert/strict');
const route=require('./association-harassment-triage').route;
const ask='我是協會聘的行政，活動結束後被主管用訊息騷擾。沒在辦公室也算工作場所的問題嗎？該找協會還是縣府？';
const a=route(ask);
assert.equal(a.choices.length,3);
assert.match(a.summary,/不一定/);
assert.match(route(a.choices[0].question).summary,/不在辦公室/);
assert.match(route(a.choices[1].question).summary,/不先套用/);
const mixed=route('協會有人被騷擾，還不確定性質，找誰申訴或處理？');
assert.equal(mixed.choices.length,4);
assert.match(route(mixed.choices[1].question).summary,/事發地警方/);
assert.equal(route(a.choices[2].question).choices.length,3);
const b=route('更正，對方是我們協會的最高負責人，協會聘不到十個人，也沒有申訴窗口。我還要先向他本人反映，還是可直接向勞工主管機關申訴？',a.triageContext);
assert.match(b.summary,/不用先找|可直接向/);
assert.match(JSON.stringify(b.steps),/不等於雇主得不處理/);
const c=route('我們協會辦公開活動，志工和民眾被參加者性騷擾；對方不是上司也不是老師。要求離場、先轉介誰、可以公布姓名嗎？');
assert.match(c.summary,/事發地警方/);
assert.match(JSON.stringify(c.steps),/場地管理權/);
const d=route('再確認：我在協會做志工，不是受僱；另有一位領薪工作人員，同一個人在活動現場騷擾我們兩人。誰處理、誰可保留紀錄？',c.triageContext);
assert.match(d.title,/個別身分分流/);
assert.match(JSON.stringify(d.steps),/不特定人於公共場所/);
assert.match(route('更正：不是性騷擾，是協會員工覺得被主管霸凌，怎麼申訴？',d.triageContext).summary,/不先套用/);
assert.equal(route('另問：佳冬鄉學術文化團體有幾個存續？',d.triageContext),null);
assert.equal(route('協會想找志工，培訓和證照怎麼辦？'),null);
assert.equal(route('某協會理事長不開會怎麼辦？'),null);
console.log('harassment: scoped pathways, confirmation, mixed incidents, privacy and topic reset passed');
