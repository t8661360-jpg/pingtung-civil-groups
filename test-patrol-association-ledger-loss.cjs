'use strict';
const assert=require('node:assert/strict');
const {ledgerLoss:answer}=require('./association-ledger-loss');
const text=x=>x.steps.flat().join(' ');
const original=answer('協會的帳冊被水淹壞了，要報縣府嗎，怎麼補');
assert.match(original.summary,/沒有統一的三十日報縣府規定/);
assert.match(text(original),/至少保存十年.*未結事項/);
assert.match(text(original),/不能冒充原件/);
assert.equal(original.choices.length,3);
const [plain,tax,grant]=original.choices.map(x=>answer(x.question));
assert.equal(plain.choices,undefined);
assert.match(plain.summary,/一般協會會務沒有統一/);
assert.doesNotMatch(text(plain),/儘快通知原補助機關/);
assert.doesNotMatch(text(plain),/次日起三十日內申請/);
assert.match(text(tax),/財政部營所稅.*次日起三十日內申請/);
assert.match(grant.summary,/銀行對帳單只能提供佐證/);
const both=answer('協會帳簿因火災滅失，稅務帳簿跟補助核銷憑證，要報國稅局還是補助的局處？');
assert.match(text(both),/轄區國稅局.*原補助機關/);
assert.match(both.summary,/國稅局.*原補助機關/);
for(const q of ['合作社的帳冊泡水保存多久？','協會帳簿正常保存幾年？','協會郵局存摺遺失了要掛失','協會會址泡水申請房屋稅減免嗎？','協會帳冊沒有泡水，只想問保存規定']) assert.equal(answer(q),null,q);
console.log('association ledger damage routing OK');
