const assert=require('node:assert/strict');
const {route}=require('./meeting-notice-calendar.js');
const now=new Date('2026-11-28T15:00:00Z'), ask=(q,p)=>route(q,now,p), steps=a=>JSON.stringify(a.steps);
const a=ask('協會的會員大會已訂在明年三月六日，想先開理事會，不知道兩場各要提前多久通知？');
assert.match(steps(a),/會員（代表）大會：通常15日前通知.*2027年2月19日.*理事會：通常7日前通知.*這場的開會日期還沒確認/);
assert.equal(a.nextNoticeDate.kind,'directors');
assert.match(steps(ask('2027年2月15日',a.nextNoticeDate)),/2027年2月8日/);
assert.equal(ask('2027年2月15日'),null);
const b=ask('本來說理事會，改成監事會單獨查帳，只是一般開會，預計下個月5日，什麼時候發通知？');
assert.equal(b.steps.length,1);assert.match(steps(b),/監事會：通常7日前通知.*2026年12月5日.*2026年11月28日/);
const c=ask('3/5的會議得挪到3/12，會員大會的書面通知已寄了，理事會通知還沒寄；會員之前簽的委託書也寫3/5。兩場各需怎麼辦？');
assert.match(steps(c),/3月12日.*舊委託書.*理事會：通常7日前通知.*這場的開會日期還沒確認/);
assert.match(steps(ask('不是大會也不是理事會，是一般合作社的社員大會。下個月5日要開，通知提前幾日？')),/合作社社員大會：通常7日前通知.*以書面/);
const d=ask('下個月五號要開會，何時通知大家？');assert.equal(d.choices.length,4);for(const {question} of d.choices)assert.match(steps(ask(question)),/2026年12月5日/);
assert.equal(ask('信用合作社社員大會下個月五號要開會何時通知？'),null);
assert.equal(ask('成立大會下個月五號要開會何時通知？'),null);
console.log('多會議通知、日期與索引接續通過');
const shifted=ask('會員大會原訂2027年3月5日，改到2027年3月12日，理事會日期未定，兩場各何時通知？');
assert.match(shifted.steps[0][1],/會議日期：2027年3月12日.*2027年2月25日/);
assert.match(shifted.steps[1][1],/這場的開會日期還沒確認/);
