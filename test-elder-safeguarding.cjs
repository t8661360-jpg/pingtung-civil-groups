const assert=require('node:assert/strict');
const {route:r}=require('./elder-safeguarding.js');
const text=x=>[x.title,x.summary,...x.steps.flat()].join(' ');
const q='我們協會有日照點和送餐隊，志工發現長輩被鎖在宅內、疑似受傷，照顧者是配偶，有失智、身障證明，長輩要我們保密且不願離家；現場有孩童、社工今天休假、幹部要我們先傳照片等開會再通報。要先判斷安全、聯絡誰、專業與志工義務、時限、交哪些資料、如何保密、跨區和後續紀錄怎麼處理？';
const urgent=r(q);
for(const re of [/先在安全處打110/,/救護打119/,/不要等社工/,/仍可立即打113/,/最遲24小時/,/24小時內補表/,/一概沒義務/,/第75、76條/,/現場有孩子/,/不要把照片.+志工群組/,/跨區.+實際所在地/])assert.match(text(urgent),re);
const corrected=r('我更正，沒看到危險或受傷，只是長者獨居、一週沒拿到餐，說沒有家屬在身邊。是不是一定算家暴，也要打110？',urgent.elderSafetyContext);
assert.match(text(corrected),/不等於家暴/);
assert.doesNotMatch(text(corrected),/一併提報|現場有孩子|不要等社工回班/);
const social=r('更正，不是志工送餐，是協會受聘社工接案，長輩說家人鎖門、不給吃喝，但不願具名。社工要不要等主管同意、多久報、資料怎麼留？');
assert.match(text(social),/第50條.+第43條/);
const uncertain=r('我們只有聽鄰居說長輩被家人推倒，長輩也可能是自己跌倒。先問資料、直接報警、113、社政通報怎麼分，照片和地址能不能給志工群組？');
assert.match(text(uncertain),/不要等小屏選項/);
assert.equal(uncertain.choices.length,3);
const choices=uncertain.choices.map(c=>r(c.question,uncertain.elderSafetyContext));
assert.match(choices[0].summary,/110/);assert.match(choices[1].summary,/先打113/);assert.match(choices[2].summary,/送餐單位/);
assert.equal(r('櫃檯長者保護確認:urgent'),null);
assert.equal(r('換題，學生志工可以幫協會打字，不收薪，要留志工紀錄嗎？',urgent.elderSafetyContext),null);
assert.equal(r('志工搬桌子跌倒要走保險嗎？',urgent.elderSafetyContext),null);
assert.equal(r('社區老人送餐服務有幾個據點可以申請？',urgent.elderSafetyContext),null);
assert.match(r('我阿嬤沒有受傷，但是還被鎖在家裡，志工要通報嗎？').title,/立即危險/);
assert.match(r('老人沒有被鎖，也沒有傷，只是獨居最近缺餐，要通報嗎？').title,/獨居斷餐/);
assert.match(r('我阿嬤被兒子打，我要怎麼辦？').summary,/先打113.+先打110/);
assert.match(r('新題：長輩被打、怕家人知道，可以通報嗎？',urgent.elderSafetyContext).title,/疑似遭疏忽或虐待/);
console.log('elder-safeguarding emergency, protective reporting, privacy, and choice tests passed');
