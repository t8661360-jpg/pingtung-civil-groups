'use strict';
const assert=require('node:assert/strict');
const {route}=require('./association-audit-borrowing');
const {officeStatus}=require('./association-office-status');
const bare=route('理事長沒開理事會就自己決定買車，監事可以怎麼辦');
assert.match(bare.summary,/監事會.*查核合約、預算與決議/);
assert.match(bare.steps.at(-1)[1],/理事會不處理，監事會可提會員/);
const signed=route('協會會費拿去買車，理事長已經簽約但理事會沒通過，監事能直接撤銷合約嗎？');
assert.match(signed.summary,/理事會沒通過不代表契約一定無效/);
assert.match(signed.steps[2][1],/民法第27條.*善意第三人.*第170條/);
assert.match(route('屏東協會理事長私自用縣府補助買車，監事怎麼查？').steps.flat().join(' '),/汽機車列為不予補助/);
assert.equal(route('合作社理事長沒開理事會就自己決定買車，監事可以怎麼辦'),null);
assert.equal(route('協會理事長買車要怎麼辦車籍登記？'),null);
const judge=officeStatus('我們理事長被判有期徒刑確定，判決有褫奪公權，還能當協會理事長嗎？');
assert.match(judge.steps[0][1],/刑法第36條.*公務員和公職候選人/);
assert.match(judge.summary,/不能保證一定能留任.*實際出缺/);
const vacancy=officeStatus('理事長褫奪公權，如果章程明文還可以留任嗎，還是要辦理補選？');
assert.match(vacancy.steps[2][1],/一個月內補選.*不足六個月.*不是從刑事判決日一律起算/);
assert.equal(officeStatus('合作社理事長被褫奪公權還能當嗎？'),null);
assert.equal(officeStatus('理事長會被褫奪公權多久？'),null);
