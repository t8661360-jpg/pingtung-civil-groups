const assert=require('node:assert/strict');
const {route,follow}=require('./charitable-fundraising-stages');
const txt=a=>[a.summary,...a.steps.flat()].join(' ');
const cases=[
 ['屏東的立案協會還沒辦法人登記，只有朋友主動送一箱物資、我們沒發文。物資可以收嗎，又可以把轉帳帳號放在社群請外人一起捐嗎？',['其他收入','正式團體收據','不能用一般立案協會的名義']],
 ['我們一般協會不是政治募款，原先只在限定會員群組募集，會員把文轉到公開社群，匯款還進理事長個人帳；這仍算會員內募嗎、誰應該開收據、先怎麼處理？',['會員自行轉貼不代表','停止讓款項繼續進個人帳','依法返還']],
 ['屏東公益社團法人有縣府的許可，期間只在屏東；有人要求我們把同一活動以直播向外縣市觀眾募集。能同一張許可繼續用、可以事後補辦嗎、原收的錢怎麼列帳、可以改用途嗎？',['七日前報主管機關許可','活動地區','先募再補','捐款專戶與專簿','返還其捐贈財物']],
 ['先問能不能改用：屏東已獲許可的募款活動已結束，部分捐款指定買輪椅、剩下想辦志工便當、另有一筆政府補助，人還問要什麼時候公告收支、贈物不經帳戶怎麼列、捐款人不同意時要退嗎、能用身分證照片附在公開徵信嗎？',['次日起三十日','再於三十日內','不能先拿來買便當','政府','收據存根','期限內異議者','證號']],
 ['有辦公益社團法人登記，我們沒對外邀請，外人主動捐物資，至少多久公告一次，年底後要不要報備？',['不走對外勸募許可','至少每六個月','年度終了後五個月']],
 ['我們是屏東公益社團法人，只有官網募款，網址全台能看到但不辦外縣市現場活動。申請向屏東還是衛福部？',['會址在屏東就是屏東縣政府','網站全台可見不必然']],
 ['收到捐贈想公開徵信，我們可以不要放捐贈者的身分證照片嗎？帳上要留什麼？',['不必放身分證照片','至少保存五年','至少十年']]
];
for(const [q,terms] of cases){const a=route(q);assert.ok(a,q);for(const s of terms.filter(x=>x!=='政府'))assert.ok(txt(a).includes(s),s+' '+q);}
const unknown='有人私訊想自己送物資，也有人說要幫我們轉帳。我們協會要先分什麼、要怎麼知道算不算募款？';
assert.equal(route(unknown).choices.length,3);
for(const [i,x] of route(unknown).choices.entries()){assert.ok(x.question.startsWith(unknown)); const b=route(x.question);assert.ok(!b.choices);assert.match(txt(b),[/其他收入/,/取得許可/,/會員內募/][i]);}
const next='補充：已辦公益社團法人登記，從頭沒貼帳號只讓對方自己送，這個需要申請勸募許可嗎，何時把收支報備？';
assert.ok(follow(next));assert.match(txt(route(unknown+'；'+next)),/年度終了後五個月/);
for(const q of ['候選人募政治獻金，不是協會募公益捐款，可以直接用公益勸募字號嗎？','公益勸募條例第18條','協會收會員會費要開收據嗎？','寺廟公開募香油錢和宗教活動經費要什麼許可？','收到捐款去國稅局所得稅申報要怎麼辦？'])assert.equal(route(q),null,q)
