'use strict';
const assert=require('node:assert/strict');const {route}=require('./meeting-proxy-scope');
const all=x=>JSON.stringify(x);
const mixed=route('社區發展協會會員大會同一天要改選和通過決算，我本人不能到，想把兩件事分別委託兩個會員，可以這樣做嗎？委託進場的人還有別人的一份。');
assert.match(mixed.title,/不重複分派/);assert.doesNotMatch(all(mixed),/先書面終止委託/);
for(const s of ['同一類別','已受另一名會員委託者不能再代理您','不把同一人拆成兩次出席'])assert.ok(all(mixed).includes(s),s);
const personal=route('協會選理監事的會員大會，我先簽書面代理，開會那天能去了。他還沒投票，我簽到就好還是要把委託書撤回？');
assert.match(all(personal),/第7條第3項/);
assert.match(all(personal),/不能自己再投一票/);
const co=route('普通合作社下午要開社員大會，選理監事與審決算，緊接著開理事會，我既是社員也是理事。我先委託另一名有資格的社員，他已有別人委託、只寫原日期、可能當選理事、他先簽到了但還沒投票，現在我自己能到。誰要撤回、誰當場報到、票能不能重投、怎樣分開兩個會議紀錄、是否可代我出席理事會？');
for(const s of ['第50條','第53、54條','章程','建議帶書面撤回','不自行拿第二張票','分開造具簽到與紀錄'])assert.ok(all(co).includes(s),s);
assert.doesNotMatch(all(co),/第7條第3項/);
const next=route('更正：其實不是合作社，也不是理事會，是我們社區發展協會會員大會改選；本人會出席，代理人還沒投票。',co.meetingProxyScopeContext);
assert.match(all(next),/第7條第3項/);
assert.doesNotMatch(all(next),/第50條|第53、54條|本人出席，不可委託/);
const unknown=route('我沒辦法去開會，可以讓別人代投嗎？');
assert.equal(unknown.choices.length,4);
const titles=unknown.choices.map(o=>route(o.question,unknown.meetingProxyScopeContext)?.title);
assert.equal(new Set(titles).size,4);
for(const q of ['會員大會改期到下週，原委託書可以留著嗎？','信用合作社理監事會可以委託嗎？','新題：來義鄉有哪些社區發展協會？'])assert.equal(route(q,co.meetingProxyScopeContext),null,q);
