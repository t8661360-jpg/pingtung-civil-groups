'use strict';
const assert=require('node:assert/strict');
const {route,adjust}=require('./association-borrowed-equipment');
const content=r=>r.summary+' '+r.steps.flat().join(' ');
let input='我們協會消防器材是向里辦公處借的，準備解散時能送給別的社團嗎？';
let a=route(input);assert.match(content(a),/借用器材.*不能跟協會財產一起送.*清點歸還/);
assert.match(content(a),/會員（代表）大會依法作決議/);
assert.equal(a.choices,undefined);
const amb='我們協會要解散，縣府補助買的設備、家屬捐的錢和貼里辦公處貼紙的器材可以先送給別的團體嗎？';
a=route(amb);
assert.equal(a.choices.length,2);assert.match(content(a),/貼紙不能認定所有權/);
assert.match(content(route(a.choices[0].question)),/按借用紀錄.*清點歸還/);
assert.match(content(route(a.choices[1].question)),/依法受贈入帳.*仍須查用途條件/);
const fix='更正，不打算解散，也沒有核准勸募，只有租公所場地、要開理事會表決付修繕費，器材是借的；理事長不是里長。';
a=route(adjust(input,fix));assert.match(content(a),/沒有解散就按現在的借用或租用走/);
assert.doesNotMatch(content(a),/會員（代表）大會依法作決議|原勸募案不要混進/);
const end='協會實際要解散，會員大會還沒開，有投票、已承諾給另一個團體的借用器材、縣府補助物品及未核銷款、工資、未付租金、帳上無指定捐款、過期核准勸募、還有一位理事說把存摺交給新團體就好。哪些要停止、查資料、找原機關或法院，怎麼排序？';
a=route(end);for(const p of [/未支用餘款/,/不能先交設備或存摺/,/勞基法第28條/,/逾期募集所得.*返還捐贈人/])assert.match(content(a),p);
for(const n of ['我是里長，現在想當協會理事長，可以兼任嗎？','合作社向公所借音響，要解散了能送人嗎？','協會要解散，核准勸募剩餘、借用器材和員工薪資怎麼辦？'])assert.equal(route(n),null,n);
a=route('我們協會把租借的器材弄壞，要先修還是先還？');
assert.match(content(a),/約定清點歸還.*正常磨損/);
a=route('我們協會想把縣府核准買的設備跟貼有里辦公處貼紙的器材送人，有些會費還沒繳，可以一起交接嗎？');
assert.match(content(a),/貼紙不能認定所有權/);
assert.equal(a.choices.length,2);
assert.doesNotMatch(content(a),/會員（代表）大會依法作決議/);
