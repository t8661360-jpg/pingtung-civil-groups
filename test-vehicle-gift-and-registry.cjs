const assert=require('node:assert/strict');
const {route}=require('./vehicle-gift-and-registry');
const j=JSON.stringify;
const q=route('同事想把機車送給我們協會，該去哪過戶、協會要列財產、開捐贈證明嗎？');
assert.match(j(q),/團體正式證明文件及財稅機關編配的統一編號.*財產登記簿.*以團體全名開捐物收據/);
const a=route('志工的舊機車要捐給社區協會，但只有縣府立案沒法院法人登記，要不要先問監理站、能不能記入財產、是否有第三人還在使用、哪一種收據可以開？');
assert.match(j(a),/請洽監理站.*不能說一律不准或保證可登記.*第三人|請洽監理站.*不能說一律不准或保證可登記.*仍外借/);
const h=route('我們社區發展協會已有法院登記。別人要贈送一輛六年以上機車給我們送餐，還有舊牌照、強制險、被借去用與前車主口頭限用途。可否先用、要去哪過戶帶什麼、理事長名字可否代團體、要怎麼列財產、付修理費可否拿已核定的補助、能開捐物證明給他扣稅嗎？');
for(const re of [/扣稅洽國稅局/,/已辦法院登記/,/出廠5年以上/,/剩餘效期須至少30日/,/不等於已符合|不表示已符合/,/指定用途要留書面/,/修理費或保險費能否用補助/])assert.match(j(h),re);
const r=route('更正，剛才車不是贈送給協會，是個人向車行租的機車，只想知道怎麼換行照或名字，不問捐贈與補助。',h.vehicleRegistryContext);
assert.match(j(r),/登記車主.*租賃契約/);
assert.doesNotMatch(j(r),/財產登記簿|國稅局|修理費或保險費能否用補助/);
assert.equal(r.vehicleRegistryContext.grant,false);
assert.match(route('我只換自己的租用機車行照，不是協會的。').title,/租車行照/);
const u=route('機車要換名字，哪裡辦？');
assert.equal(u.choices.length,3);
assert.match(route(u.choices[2].question,u.vehicleRegistryContext).summary,/公路監理所站/);
assert.match(route('機車駕照怎麼考？').summary,/不是人民團體櫃檯的業務/);
assert.equal(route('補助可以買機車嗎'),null);
assert.equal(route('一般協會土地要怎麼過戶？'),null);
assert.equal(route('佳冬鄉文化類團體有幾個？',r.vehicleRegistryContext),null);
console.log('vehicle-gift-and-registry OK');
