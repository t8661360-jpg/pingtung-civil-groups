const assert=require('node:assert/strict');
const {route}=require('./grant-project-closeout');
const str=x=>JSON.stringify(x);
const q='我們是有限責任合作社，股金有繳，補助有未用的錢、錯報收據、做完但沒請款的費用、補助買來的列管機器、跟公所借來的桌椅。有理事只是經手，另位社員另外簽了保證。準備解散，怎麼處理？';
const c=route(q);
for(const re of [/餘款要繳回/,/原憑證/,/20日/,/納入團體財產/,/點交/,/合作社解散後/,/認購股額/,/另行簽的保證/])assert.match(str(c),re);
const fixed=route('不是要解散，是合作社繼續做，只是這筆補助到期，剛提的錢、單據跟東西還是要處理。',c.grantCloseoutContext);
assert.match(fixed.title,/只結補助案/);
assert.match(str(fixed),/納入團體財產.*點交/);
assert.doesNotMatch(str(fixed),/合作社解散後/);
const a=route('是已登記的社團法人，現在真的要解散。核銷還沒完成、帳戶還有餘款、補助有買一臺還在列管的機器，另外有借公所的設備。是理事長還是清算人處理？縣府跟法院各找誰？');
assert.match(str(a),/15日內向法院報告/);
assert.match(str(a),/納入團體財產.*點交/);
const m=route('補助案結束，剩下的錢和東西怎麼辦？');
assert.equal(m.choices.length,2);
const e=route(m.choices[1].question,m.grantCloseoutContext);
assert.equal(e.choices.length,3);
const u=route(e.choices[1].question,e.grantCloseoutContext);
assert.match(str(u),/由理事長或章程所定代理人/);
assert.doesNotMatch(str(u),/15日內向法院/);
const p=route(m.choices[0].question,m.grantCloseoutContext);
const b=route(p.choices[1].question,p.grantCloseoutContext);
assert.match(str(b),/清點歸還/);
assert.doesNotMatch(str(b),/納入團體財產/);
const n=route('我們的社區發展協會還在運作，活動結束後發現有一筆發票報錯了、一筆核准的支出已經付了但還沒請款，手邊還有剩款，理事長要先做什麼、要自己賠嗎？');
assert.match(n.choiceHeading,/經費/);
assert.match(route(n.choices[1].question,n.grantCloseoutContext).title,/自籌活動/);
assert.match(str(route(n.choices[0].question,n.grantCloseoutContext)),/理事長.*自己墊付/);
assert.equal(route('佳冬鄉文化類團體有幾個？',fixed.grantCloseoutContext),null);
assert.equal(route('商業同業公會解散，補助餘款和設備怎麼處理？'),null);
assert.equal(route('一般協會收到補助還沒撥款怎麼入帳？'),null);
const issue=route('社區發展協會解散時還有補助款沒核銷，理事長要用個人財產賠嗎？');
assert.match(str(issue),/團體退款和個人賠償是兩回事/);
assert.match(str(issue),/20日/);
assert.equal(issue.grantCloseoutContext.asset,false);
console.log('grant-project-closeout OK');
