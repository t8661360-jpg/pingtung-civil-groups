for(const q of ['信用合作社清算報告多久要送？股息上限？','合作社的清算報告多久要送？','合作社股息上限是多少？','不住屏東還能加入協會嗎？','理事長可以把會員踢掉嗎？','合作社的清算報告多久要送？股息有上限嗎？怎麼報稅？','協會8月開會收支報告要做到哪天？'])assert.equal(answer(q),null,q);
