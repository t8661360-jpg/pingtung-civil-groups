const assert=require('node:assert/strict');
const {route:r}=require('./administrative-relief.js');
const text=x=>[x.title,x.summary,...x.steps.flat()].join(' ');
const missing=r('協會報縣府核備被要求補件，但通知只寫缺資料沒列清單，補件期限快到了，可以先送現有的並問要哪些嗎？');
assert.match(text(missing),/通常不是最後的駁回.+先送目前已有/);
assert.match(text(missing),/未獲准不要當成期限已延長/);
const decision=r('更正，已經收到一張寫不予核備的正式公文，理由只有文件有缺，會期已過；是再補文件、提訴願還是兩個都要做？',missing.administrativeReliefContext);
assert.match(text(decision),/不會自動停止或延長訴願期限/);
assert.match(text(decision),/次日起一般30日.+收受為準/);
assert.match(text(decision),/經原行政處分機關.+不必等機關答補件/);
const changed=r('那如果只有承辦用LINE提醒有缺，沒有准駁公文，是不是立刻就要訴願？',decision.administrativeReliefContext);
assert.match(text(changed),/不用只因收到這封就立刻訴願/);
assert.doesNotMatch(text(changed),/次日起一般30日/);
const forced=r('縣府是對外協會立案申請駁回，不只是請補件，從電子公文看到和紙本送達不同日，什麼時候起算、去哪裡提出、補送資料會不會停掉期限？');
assert.match(text(forced),/先查|先看救濟/);
assert.match(text(forced),/第68條允許依法規以電子文件送達/);
const unk=r('縣府來函，我們看不出也不確定是補件、駁回還是其他行政處分，現在要怎麼做？');
assert.equal(unk.choices.length,3);
assert.match(r(unk.choices[0].question,unk.administrativeReliefContext).title,/補件提醒/);
assert.match(r(unk.choices[1].question,unk.administrativeReliefContext).title,/正式不予核備或駁回/);
assert.match(r(unk.choices[2].question,unk.administrativeReliefContext).title,/先核對送達/);
assert.match(r('縣府只說資料不完整要補件，未駁回，有需要馬上訴願嗎？').title,/補件提醒/);
assert.equal(r('協會會員大會閉會後多久報縣府核備？'),null);
assert.equal(r('法院支付命令送達後多久提出異議，要不要補件？'),null);
assert.equal(r('換題，協會辦售票純音樂會，還要辦娛樂稅免徵嗎？',missing.administrativeReliefContext),null);
assert.equal(r('櫃檯行政函確認:missing'),null);
console.log('Administrative relief procedural, decision, period, and choice checks pass');
