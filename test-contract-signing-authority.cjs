const assert=require('node:assert/strict');
const {route}=require('./contract-signing-authority');
const j=JSON.stringify;
const a=route('協會理事長沒有經過理事會同意就蓋章簽約，契約有效嗎？');
assert.equal(a.choices.length,2);
const r=route(a.choices[0].question,a.contractSigningContext);
assert.match(j(r),/民法第27條.*不得對抗善意第三人/);
assert.equal(r.contractSigningContext.role,'rep');
assert.equal(r.contractSigningContext.internal,true);
assert.equal(r.choices,undefined);
assert.match(j(r),/不要只因沒開會就自行拒付尾款/);
const p=route('這是已登記的社團法人，章程說租場要先經理事會，理事長卻用協會名義簽了，房東說不知道，已有付款，協會可直接不付尾款嗎？');
assert.match(j(p),/法人董事.*聲稱不知道.*不由小屏判定善意/);
const un=route('社區發展協會只有縣府立案、沒辦法院法人登記。秘書長代簽兩年租約，沒找到授權，房東知道他不是理事長，理事會後來才收到合約，補助承辦也還沒核准。可追認嗎？能把這筆上報核銷嗎？');
assert.match(j(un),/不要直接套法人董事規定.*事後補開會.*不是一律等於已追認.*未核准或用途有疑義/);
assert.doesNotMatch(j(un),/不得對抗善意第三人/);
const mix=route('我們是法院登記的公益社團法人，理事長不等理事會同意就不只租場，還把補助買的自有設備當押、印章蓋了、租金先付、公所借用的器材也寫在附件。廠商原先看過章程、會計說要報補助、監事要調帳，新理事會能不能改決議，對方還要求違約金。哪些事先停，誰查什麼，法律效力跟核銷是不是一樣？');
assert.match(j(mix),/違約金通知.*監事會可依.*對方曾看過章程.*合約效力不是補助核銷資格.*公所借來的器材不是團體自有/);
const c=route('更正，剛講的是一般合作社，不是社團法人，改由經理簽的，不是理事主席。理事會沒同意，沒有補助款，只是一般倉庫租約，能算數嗎？',mix.contractSigningContext);
assert.match(j(c),/合作社法第34條.*經理、會計或其他員工不單憑職稱/);
assert.doesNotMatch(j(c),/民法第27條對法人董事|合約效力不是補助核銷資格|公所借來的器材/);
const unknown=route('是我們團體的人沒有授權就簽約，我不知道有沒有辦法人登記。');
assert.equal(unknown.choices.length,3);
const who=route(unknown.choices[1].question,unknown.contractSigningContext);
assert.match(who.choiceHeading,/由誰簽約/);
const aft=route(who.choices[1].question,who.contractSigningContext);
assert.match(j(aft),/事後補開會.*不是一律等於已追認/);
const special=route('信用合作社理事擅自簽貸款，跟一般合作社簽租約一樣嗎？');
assert.match(j(special),/信用合作社法.*不能直接照一般合作社|不能直接照一般合作社.*信用合作社法/);
assert.equal(route('新題：佳冬鄉文化類團體有幾個？',c.contractSigningContext),null);
assert.equal(route('社區活動中心借場，租約需要哪些文件？'),null);
console.log('contract-signing-authority OK');
