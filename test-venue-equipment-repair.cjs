const assert=require('node:assert/strict');
const {route}=require('./venue-equipment-repair');
const j=JSON.stringify;
const u=route('社區活動中心冷氣壞了誰要修？');
assert.equal(u.choices.length,4);
const p=route(u.choices[0].question,u.venueRepairContext);
assert.match(j(p),/先找管理公所/);
const b=route(u.choices[1].question,u.venueRepairContext);
assert.match(j(b),/通知原出借方/);
const a=route('活動中心是公有、協會代管，冷氣是公所財產，師傅說超過保固要換；不知道代管契約寫小修、大修誰出、我們可不可以先簽會議紀錄說用補助買新的？');
assert.equal(a.venueRepairContext.owner,'public');
assert.match(j(a),/日常維護與大修.*過保不代表.*原補助承辦/);
const h=route('我們是社區協會用縣府核定經費買冷氣，裝在公所場館，仍有保固、財產卡有列管，重複漏水、旁邊有插座、下週還有借場活動。可報修還是一定要報廢，核銷可以用補助尾款嗎？');
assert.equal(h.venueRepairContext.owner,'own');
for(const re of [/不要碰潮濕的插座/,/有保固先報修/,/不要拿補助餘款先墊/,/改場地、延期或暫停/])assert.match(j(h),re);
const r=route('租屋契約是協會和私人屋主簽，冷氣原本是屋主的配備，漏水靠近插座、明天辦共餐、屋主說自己先叫修；沒有看到修繕條款、屋主未給書面同意、會計想先拿補助餘款墊錢再從房租扣、理事長想改場地，誰要通報、要不要取消？');
assert.match(j(r),/第429條.*契約另訂.*第430條.*屆期仍不修/);
const c=route('更正，剛說的冷氣不是屋主的是公所出借，協會仍租私人屋主的場館，有漏水，這次沒有補助。',r.venueRepairContext);
assert.match(j(c),/通知房東及出借方/);
assert.doesNotMatch(j(c),/修繕費能否報補助|第429條原則由出租人修繕/);
const near=route('公所管的社區活動中心，社區協會只是借來上一堂課，冷氣不會動，找誰叫修、場地費裡面有算嗎？');
assert.equal(near.venueRepairContext.owner,null);
assert.match(j(near),/只借一個時段.*冷氣使用費也不一定包含維修/);
assert.equal(route('我家冷氣不冷了，找誰修？'),null);
assert.equal(route('協會買了冷氣誰要負責保管'),null);
assert.equal(route('新題：佳冬鄉文化類團體有幾個？',c.venueRepairContext),null);
console.log('venue-equipment-repair OK');
