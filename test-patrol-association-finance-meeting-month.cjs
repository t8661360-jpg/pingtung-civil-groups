assert.equal(start(q).kind,null);
assert.deepEqual(dateOf('民國115年8月15日'),{y:2026,m:8,d:15});
assert.deepEqual(dateOf('2024-03-03'),{y:2024,m:3,d:3});
assert.deepEqual(dateOf('八月十五日'),{y:null,m:8,d:15});
