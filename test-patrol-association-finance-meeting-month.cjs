const assert=require('node:assert/strict');
const {dateOf,start,meetingType,answer}=require('./association-finance-meeting-month');
const q='協會8月開會，請問收支報告要做什麼時候';
assert.deepEqual(start(q),{q,kind:null,date:{y:null,m:8,d:null}});
assert.deepEqual(dateOf('民國115年8月15日'),{y:2026,m:8,d:15});
assert.deepEqual(dateOf('2024-03-03'),{y:2024,m:3,d:3});
assert.deepEqual(dateOf('八月十五日'),{y:null,m:8,d:null});
assert.equal(dateOf('115年2月29日'),null);
assert.equal(dateOf('2026-04-31'),null);
assert.equal(dateOf('2026-08-00'),null);
assert.equal(dateOf('13月'),null);
assert.equal(meetingType('會員（代表）大會'),'assembly');
assert.equal(meetingType('理事會／監事會'),'boards');
assert.equal(meetingType('理監事聯席會議'),'joint');
assert.equal(meetingType('監事會'),'supervisor');
assert.equal(meetingType('理事會'),'board');
assert.equal(meetingType('理事會還是會員大會'),null);
const exact=start('協會115年8月15日召開會員大會，收支決算哪一年？');
assert.match(answer(exact).title,/2026年8月15日 會員（代表）大會/);
const result=s=>answer(s).steps.join('\n');
assert.match(result(exact),/2025年（上年度）1月1日至12月31日.*2026年3月底前/);
assert.match(result(exact),/監事會審核.*大會追認，再報主管機關備查/);
assert.match(result(exact),/2026年1月1日至7月31日.*不是法定申報截止日，也不取代/);
assert.match(result({kind:'board',date:dateOf('2024-03-10')}),/不能代替大會[\s\S]*2月29日/);
assert.match(result({kind:'supervisor',date:dateOf('2026-10-20')}),/審核，不是編造決算[\s\S]*9月30日/);
assert.match(result({kind:'joint',date:dateOf('2026-01-01')}),/追認[\s\S]*尚未有已結帳期間/);
assert.match(result({kind:'boards',date:dateOf('2026-01-03')}),/1月2日/);
for(const x of ['協會的會計報告什麼時候做？','我們協會的會員大會一定得在一月開嗎？','合作社8月開會員大會收支決算怎麼做？','協會八月開會員大會要交補助核銷收支報告','協會8月開成立大會要附收支報表嗎？','協會會員大會要準備哪些財務報表？'])assert.equal(start(x),null,x);
console.log('association finance meeting date planner OK');
