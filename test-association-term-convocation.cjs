'use strict';
const a=require('node:assert/strict');
const route=require('./association-term-convocation');
const p=x=>[x.title,x.summary,...x.steps.flat(),...x.refs.map(y=>y.title)].join(' ');
const exact=route('理事長任期滿了，還沒改選前可以召開臨時會員大會嗎');
a.match(exact.summary,/若是一般協會.*不能依法召集.*第32條/);
const permit=route('一般協會理事長這週到期，主管機關已准延後辦改選。會員現在想開臨時大會，還能直接以舊理事長名義通知嗎？');
a.match(permit.summary,/展延.*有效任期.*核准函/);
a.match(p(permit),/不能只憑舊圖記、頭銜或核准改選展延/);
const petition=route('協會五分之一會員雙掛號連署開臨時大會，理事長收到超過30天了仍未召開；有幾位主張自己簽通知。是自行發還是請縣府指定？');
a.match(petition.summary,/不是自行發通知.*收到書面連署逾30日.*指定理事/);
a.match(p(petition),/第15條.*雙掛號.*取得回執.*第32條指定理事一人/);
a.match(p(petition),/不是替團體選出新理事長/);
const trade=route('不是協會，是商業同業公會。理監事已到期，沒產生新理事長，主管機關要求儘速改選，原任能召集臨時大會嗎？商業團體和一般協會同一套嗎？');
a.match(p(trade),/商業團體法第27條.*仍行使職權/);
a.match(p(trade),/70年5月12日函.*不是對一般協會/);
const first=route('協會已經改選出理事但第一次理事會還沒開；上一任理事長也離開國外，負責人異動沒送縣府，租約快到期。最先用誰通知、誰可代簽，以及要不要先備查？');
a.match(first.summary,/逾期不召集.*得票最多.*代簽租約/);
a.match(p(first),/閉會後第7日至第15日.*代表/);
const correction=route('更正，我不是問開會，只問一般協會理監事改選展延最多多久、可以自己決定嗎？');
a.match(correction.summary,/不能自行.*最多三個月/);
a.doesNotMatch(correction.summary,/租約/);
const m=route('我們協會的理事長一直沒開會員大會，會員有連署，也有租約快到期，但我不知道他的任期到底到了沒有。可以先自己發通知嗎？');
a.equal(m.choices.length,4);
a.match(route(m.choices[0].question).summary,/在有效任期/);
a.match(route(m.choices[1].question).summary,/任期已屆滿/);
a.match(route(m.choices[2].question).summary,/第一次理事會/);
a.equal(route(m.choices[3].question).choices,undefined);
const long=route('社區發展協會下月才改選，原任已到期、沒有延長核准、理事長也失聯。會員想用五分之一連署、還希望大會順便改選和核過新租約，通知要誰簽、哪些事能同次處理？');
a.match(p(long),/失聯.*確認第32條.*改選與租案先列清楚.*第5條名冊/);
for(const q of ['協會會員明年5月10日要開會員大會，幾號前要通知？','協會原理事長任期滿一年還沒改選，可否用舊印章續簽三年租約？','一般合作社社員大會要展延多久？','新題：九如鄉文化團體有多少？','一般協會候選人入會滿一年才能選理事嗎？'])a.equal(route(q),null,q);
