'use strict';
const assert=require('node:assert/strict');
const {route}=require('./civil-mediation-triage.js');
const both=route('我們協會的租金調解來函，不確定是法院還是鄉公所，總幹事可否代理？');
assert.equal(both.civilMediationContext.kind,'unknown');assert.equal(both.choices.length,3);
const [court,town,unknown]=both.choices.map(x=>route(x.question,both.civilMediationContext));
const check=(x,re)=>assert.match(JSON.stringify(x),re);
check(court,/第70條的特別委任/);check(court,/聲請強制執行/);
check(town,/自調解成立日起10日內送法院/);check(town,/聲請後7日內發給/);
assert.equal(unknown.choices,undefined);
const direct=route('不是欠薪，也不是支付命令。屏東地院租金調解，協會總幹事可否簽和解？');
assert.equal(direct.civilMediationContext.kind,'court');
const reverse=route('不是鄉公所，是屏東地院寄民事調解通知，總幹事可代理嗎？',town.civilMediationContext);
assert.equal(reverse.civilMediationContext.kind,'court');
const coop=route('是合作社不是協會，公所調解租金，職員能代理簽和解嗎？');
check(coop,/合作社法第34條/);
check(route('那調解書是誰核定？',coop.civilMediationContext),/不是社會處/);
check(route('那主管機關核定了嗎，我說的是公所調解送法院看的那一步，不是收到支付命令。',coop.civilMediationContext),/不是社會處/);
assert.equal(route('換題，標準會員大會多久通知？',coop.civilMediationContext),null);
assert.equal(route('員工欠薪，我們協會可否請總幹事代理勞資調解？'),null);
assert.equal(route('我們協會收到法院支付命令，總幹事可以代簽嗎？'),null);
assert.equal(route('合作社理事監事發通知，怎麼開會？'),null);
console.log('Civil mediation representation, routes, execution and reset passed');
