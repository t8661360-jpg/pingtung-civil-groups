'use strict';
const assert=require('node:assert/strict');
const {route}=require('./association-roster-election-exceptions');
const formal=route('協會五分之一會員已書面連署要求開臨時大會，來不及另開理事會審名冊，可以用上次的名冊嗎？');
assert.match(formal.steps[0][1],/五分之一以上書面連署.*最近一次經理事會審定.*雙掛號.*30日/);
assert.match(formal.steps[1][1],/多數理事確因出會.*由大會辦理審定/);
const ordinary=route('協會的定期會員大會沒有開理事會重新審會員名冊，大會還能照開嗎？');
assert.match(ordinary.steps[0][1],/15日前.*不是只要理事缺席/);
const unknown=route('協會開會員大會來不及審會員名冊，可以用舊的嗎？');
assert.equal(unknown.choices.length,2);
for(const x of unknown.choices)assert.ok(route(x.question).steps.length>=2);
const past=route('社團法人協會年度會員大會已經開完，沒有審名冊，決議是否無效？');
assert.match(past.steps[2][1],/第58條.*3個月.*當場表示異議/);
const postal=route('協會章程有規定郵寄投票，會員大會用視訊開，理監事可以直接在線上選嗎？如果另外郵寄選票呢？');
assert.match(postal.summary,/不能直接在視訊上遠端選理監事/);
assert.match(postal.steps[1][1],/45日前.*30日前.*紙本.*備查/);
const recall=route('協會會員大會可不可以用視訊投票罷免監事，也能郵寄選票嗎？');
assert.match(recall.steps[1][1],/不授權以郵寄或視訊方式罷免/);
assert.equal(route('協會改選結果要郵寄給理事嗎？'),null);
assert.equal(route('合作社社員大會視訊選理事可以郵寄嗎？'),null);
assert.equal(route('協會會員大會審定會員名冊後可以影印嗎？'),null);
