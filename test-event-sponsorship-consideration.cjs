'use strict';
const assert=require('node:assert/strict');
const {route}=require('./event-sponsorship-consideration.js');
const check=(r,m)=>assert.match(JSON.stringify(r),m);
const t=route('協會拿店家飲水換冠名和廣告，受縣府補助，店家是理事長親屬，還要參加人電話清單，如何報帳？');
check(t,/有對價贊助/);check(t,/不直接提供參加者名單/);check(t,/不重複核銷/);check(t,/不要參與審議/);check(t,/效期/);
check(route('若不收錢只換廣告呢？',t.eventSponsorshipContext),/不收現金也可能是有對價/);
const g=route('剛剛說錯，沒有承諾任何廣告或曝光，是公司主動把飲水捐給我們，只能活動使用。',t.eventSponsorshipContext);
assert.equal(g.eventSponsorshipContext.kind,'gift');check(g,/第6條/);
assert.equal(g.eventSponsorshipContext.grant,false);
const c=route('改問合作社，不是協會公益勸募，公司給飲料換展位能開捐款收據嗎？');
assert.equal(c.eventSponsorshipContext.org,'coop');check(c,/按合作社適用會計/);
assert.doesNotMatch(JSON.stringify(c),/社會團體財務處理辦法/);
check(route('協會有店家贊助換廣告，同時公開募款，可否用同一帳？'),/分開處理有對價贊助和公開募捐/);
const unknown=route('協會有店家贊助，活動宣傳上會放商標，可以開收據嗎？我們受縣府補助。');
assert.equal(unknown.choices.length,4);
for(const x of unknown.choices)check(route(x.question,unknown.eventSponsorshipContext),/縣府補助/);
assert.equal(route('換題，協會會員大會多久前通知？',t.eventSponsorshipContext),null);
assert.equal(route('協會會員送一箱物資，可開收據嗎？',null),null);
console.log('Sponsorship exchange, genuine gifts, noncash trade and routing passed');
