const assert=require('node:assert/strict');
const {route}=require('./association-county-funding-election-checks.js');
const a=route('會員大會選舉理事時，候選人可以自己監票嗎？');
assert.match(a.summary,/沒有在相關條文明定候選人一律不得監票/);
assert.match(a.summary,/建議候選人不要負責自己參選項目/);
const b=route('協會可以用理事長的名字去申請補助嗎？');
assert.match(b.summary,/用協會全名申請/);
assert.match(JSON.stringify(b.steps),/不得存放於個人/);
const c=route('理監事會議紀錄沒報縣府，補助會不會被取消？如果大會紀錄也還沒報呢？');
assert.match(c.summary,/理監事會紀錄通常自存.*30日內/);
assert.match(JSON.stringify(c.steps),/財務資料未依規定陳報.*不予補助/);
assert.match(JSON.stringify(c.steps),/不能光因少一份紀錄就判已核定補助必然取消/);
const d=route('屏東縣協會補助可用理事長的名字嗎？理監事會議紀錄也沒報，會不會影響申請？');
assert.match(d.summary,/用協會全名申請.*理監事會紀錄通常自存/);
const e=route('協會的理事候選人可以監票嗎？另外縣府補助能用理事長個人名義申請嗎？');
assert.match(e.summary,/不得監票.*用協會全名申請/);
for(const q of ['合作社社員大會選舉，可以讓候選人來唱票嗎？','高雄市協會能用理事長名字申請補助嗎？','理監事會議紀錄怎麼寫？','協會怎麼領補助？','志工保險可以用縣府補助支付嗎？'])assert.equal(route(q),null,q);
const after=route('協會會員大會已經選完理事，候選人兼監票而且違反章程，我當天有出席，結果公告後多久可提出異議？');
assert.match(after.summary,/結果宣布之日起十五日內.*收件後十五日內/);
assert.match(JSON.stringify(after.steps),/不因候選人兼監票就自動認定整次無效/);
const absent=route('會員大會已選完理事，我沒出席；聽說候選人兼當唱票員，現在可用第25條提出異議嗎？');
assert.match(absent.summary,/沒有出席.*不能逕把自己當成同條的出席異議人/);
assert.doesNotMatch(a.summary,/書面異議|也章程/);
const routineMixed=route('民間團體的理監事會例行會議可以申請縣府活動補助嗎？協會還沒有報預決算是不是同一件事？');
assert.match(routineMixed.summary,/例行會議本身不予補助.*財務資料.*補助資格/);
assert.match(routineMixed.steps[0][1],/第5點第2款第6目/);
assert.match(routineMixed.steps[1][1],/第5點第3款第4目.*補報不能把例行會議費變成可以補助/);
const routineOnly=route('屏東協會會員大會的費用，場租可以申請活動補助嗎？');
assert.match(routineOnly.title,/例行會議不在屏東通案補助項目內/);
assert.equal(routineOnly.steps.length,1);
const financeFirst=route('屏東協會去年年度決算忘了報，另外理事會例會能申請活動補助嗎？');
assert.match(financeFirst.summary,/例行會議本身不予補助.*團體補助資格/);
assert.equal(route('屏東協會會員大會的費用能申請中央公益彩券補助嗎？'),null);
assert.equal(route('彰化縣協會例行會議可不可以申請縣府活動補助？'),null);
