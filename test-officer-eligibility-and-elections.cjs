'use strict';
const assert=require('node:assert/strict');
const {route}=require('./officer-eligibility-and-elections.js');
const all=r=>JSON.stringify(r);
const plain=route('合作社想找三位理事和兩位監事，這樣可以成立嗎？');
assert.match(all(plain),/兩位監事，名額不足/);
assert.match(all(plain),/社員資格也不能選為監事/);
const one=route('我們普通協會這屆在改選，他是正式會員，理事和監事兩邊都得票很高，可以兩邊同時就任嗎？');
assert.match(one.title,/不可同時就任/);
assert.match(all(one),/同票抽籤/);
const two=route('兩個普通社會團體各自要改選，我都是正式會員，想當甲會理事和乙會監事，兩邊章程沒寫，之後兩會可能合辦活動，能當選嗎？');
assert.match(all(two),/沒有單因各有一職就必須辭一邊/);
assert.doesNotMatch(all(two),/從社員中選出|本人不在或無法擇定/);
const mix=route('社區發展協會理事本身是另一家普通合作社的社員／候選監事，兩家今年會簽場地契約，該名理事在自己協會又同時當選監事，章程沒有特別限制，要不要解任、誰要避開表決、紀錄怎麼寫？');
for(const s of ['擇一','第40條','民法第106條','社員與社團法人總會議案','三十日內報核備'])assert.ok(all(mix).includes(s),s);
const c=route('更正：自己協會沒有選她做監事；只有在不同組織當職務，而且不會彼此簽約。',mix.officerEligibilityContext);
assert.match(all(c),/不同團體各有一職/);
assert.doesNotMatch(all(c),/本人不在|兩個組織要簽約|第106條/);
const high=route('我們勞動合作社章程寫三理事、三監事，開創立會有七名社員，有人還不是社員要當監事，一位已是同業同級合作社理事，第三位原是本社理事責任還沒解除。另有人同時拿到本社理監事當選票，票數一樣人已離開，後來本社要跟現任理事本人另外租屋，又要跟鄰里的協會合辦活動，理監事資格、擇一、誰簽、誰要迴避、報備、選票紀錄各怎麼辦？');
for(const s of ['社員資格','第15、16條','同票由會議主席抽籤','責任尚未解除','不能同時擔任兩家的理監事','第39條第1項第4款','第106條','保留票數'])assert.ok(all(high).includes(s),s);
const next=route('更正：沒有信用合作社，也沒有跟理事本人或協會簽約要處理，我現在只問一般合作社原任理事責任已解除後的監事資格，及不同社會團體兼職。',high.officerEligibilityContext);
assert.match(all(next),/責任確已解除/);
assert.doesNotMatch(all(next),/第106條|監事代表合作社這一方|同票由會議主席抽籤/);
const q=route('當上理事又當監事，現在要怎麼辦？');
assert.equal(q.choices.length,4);
const options=q.choices.map(v=>route(v.question,q.officerEligibilityContext));
assert.match(options[0].title,/同一協會/);assert.match(options[1].title,/同一合作社/);
assert.match(all(options[2]),/沒有單因各有一職就必須辭一邊/);assert.match(options[3].title,/信用合作社/);
assert.match(route('信用合作社社員能同時登記候選理事和監事嗎？').title,/不能同時登記/);
for(const s of ['新題：南州鄉有哪些社區發展協會？','一位協會理事及合作社監事，兩邊和第三人共同承租同一間房，同一人可代表簽約嗎？','協會理事長無故不開理事會，監事可以代叫人開會嗎？','協會的理事長兼會計怎麼辦？','理事長要辭職、監事能否暫代？'])
 assert.equal(route(s,high.officerEligibilityContext),null,s);
const official=route('協會理事要幾個人？合作社理事又是幾個人？');
assert.match(all(official),/理事為九至十五人且為奇數/);
assert.match(all(official),/監事至少三人、須為奇數，不得超過理事名額三分之一/);
assert.match(all(official),/一般合作社：理事、監事至少各三人/);
const arbiter=require('./answer-arbiter.js');
const q13='她在社區發展協會同一次選舉同時當選理事、監事，票數相同且人不在，另一邊又是普通合作社的社員候選監事；協會與合作社準備共辦活動、各自評議租金，該先定哪個當選、何時揭露利害、兩邊會議紀錄怎麼分？';
const addressed=route(q13);
const topics=arbiter.topicsOf([addressed.title,addressed.summary,...addressed.steps.flat()].join('｜'));
assert.ok(arbiter.topicsOf(q13).every(k=>topics.includes(k)));
const sampleCount='屏東縣的社區發展協會監事要幾名，普通合作社呢？';
const countAnswer=route(sampleCount);
assert.match(all(countAnswer),/屏東縣立案的社區發展協會/);
assert.match(all(countAnswer),/九至十五人且為奇數/);
