'use strict';
const assert=require('node:assert/strict');
const {start,noticeOnlyAnswer,cooperativeNotice}=require('./association-finance-meeting-month');
const now=new Date('2026-11-27T19:30:00Z');
const get=q=>start(q,now);
const same=get('我們是協會，理事會和會員大會都排在明年2月10日，同一天開的話兩種會議通知都幾號要送到？');
assert.deepEqual(same.pair,[['assembly',{y:2027,m:2,d:10}],['board',{y:2027,m:2,d:10}]]);
const result=noticeOnlyAnswer(same);
assert.match(result.steps[0][1],/十五日前.*2027年1月25日.*報請主管機關/);
assert.match(result.steps[1][1],/七日前.*2027年2月2日/);
assert.match(result.summary,/不是個案法定最後一天/);
const different=get('監事會2027年1月22日開，協會會員大會2027年2月10日開，分別哪一天要寄通知？');
assert.deepEqual(different.pair,[['assembly',{y:2027,m:2,d:10}],['supervisor',{y:2027,m:1,d:22}]]);
assert.match(noticeOnlyAnswer(different).steps[1][1],/2027年1月14日/);
const changed=get('原本說8月20日開會，現在改到9月3日，該哪天通知？');
assert.deepEqual(changed.date,{y:null,m:9,d:3});
assert.deepEqual(changed.linked.found,[{y:null,m:9,d:3}]);
assert.equal(changed.kind,null);
const exact=get('協會會員大會原訂2027年1月20日，改到2027年1月10日，哪天通知？');
assert.match(noticeOnlyAnswer(exact).steps[1][1],/2026年12月25日/);
assert.equal(get('協會會員大會農曆明年2月10日，幾號要通知？').needsSolar,true);
assert.equal(get('協會會員大會2027年2月30日開，幾天前要通知？'),null);
assert.equal(get('協會成立大會2027年2月10日開，哪天寄通知？'),null);
assert.equal(get('協會的監事會2027年2月10日開，緊急事故前一天可寄通知嗎？'),null);
assert.equal(get('協會在2027年2月10日開會員大會，決算和開會通知何時準備？').noticeOnly,undefined);
const mixed=cooperativeNotice('合作社開社員大會也要像協會一樣提前15天通知嗎？社員代表大會又怎麼算？');
assert.match(mixed.steps[0][1],/七日前用書面通知/);
assert.match(mixed.steps[1][1],/不能只憑名稱.*通知期限/);
assert.equal(cooperativeNotice('信用合作社的社員代表大會提前幾天通知？'),null);
