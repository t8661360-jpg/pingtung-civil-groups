'use strict';
const a=require('node:assert/strict');
const route=require('./guild-liquidation-residue');
const body=x=>[x.title,x.summary,...x.steps.flat(),...x.refs.map(r=>r.title)].join(' ');
const item=route('工業同業公會要解散，清算完後可以把剩下的財產分給會員工廠嗎？');
a.match(body(item),/民法第44條.*章程或有效大會決議/);
a.match(body(item),/若屬以公益為目的.*不得歸自然人或以營利為目的的團體/);
a.match(body(item),/法人住所所在地的地方自治團體/);
a.match(body(item),/會員代表三分之二以上出席，出席代表三分之二以上同意/);
const debt=route('我們工業同業公會打算結束，還有租金、借的設備和指定補助沒清，理事長說先按會費分錢再還債，行不行？');
a.match(debt.summary,/債務未清，不能先照會費分錢/);
a.match(body(debt),/先查所有權.*先看核定文件/);
const trade=route('不是工業同業公會，是商業同業公會，會員低於法定人數，還有剩下的錢要交給誰？');
a.match(trade.summary,/會員不足法定數額而解散.*商業會/);
a.match(body(trade),/重行組織的商業同業公會/);
a.doesNotMatch(body(trade),/工業團體法|地方自治團體/);
const shop=route('更正，只是工業同業公會自己經營的事業要停，不是要解散公會，可以直接分掉設備嗎？');
a.match(body(shop),/第41條，只清算所屬事業的財產/);
a.doesNotMatch(body(shop),/先選清算人，選不出來才聲請法院/);
a.match(route('商業同業公會經營的事業要停，不是要解散公會，可以直接分設備嗎？').summary,/權利和義務由公會承擔/);
const menu=route('我們公會要解散，債還沒付完，剩下的錢怎麼分？');
a.match(menu.summary,/先不要分/);
a.equal(menu.choices.length,3);
a.match(route(menu.choices[0].question).title,/工業同業公會/);
a.match(route(menu.choices[1].question).title,/商業同業公會/);
a.equal(route(menu.choices[2].question).choices,undefined);
a.match(body(route('工業同業公會跟商業同業公會，解散後的賸餘財產有何不同？')),/民法第44條.*第39條/);
a.match(body(route('工業同業公會解散要怎麼辦')),/工業團體法第40條/);
for(const q of ['協會要解散了，剩餘財產可以給社員嗎？','一般合作社解散後的賸餘可以分嗎','醫師公會解散剩下財產給誰？','工業同業公會的會費要怎麼算','工業同業公會少於五家會怎樣','新題：新園工業團體幾個'])a.equal(route(q),null,q);
