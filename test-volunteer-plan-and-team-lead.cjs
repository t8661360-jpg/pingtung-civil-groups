'use strict';
const a=require('node:assert/strict');
const route=require('./volunteer-plan-and-team-lead');
const p=x=>[x.title,x.summary,...x.steps.flat(),...x.refs.map(y=>y.title)].join(' ');
a.match(p(route('志工計畫書要寫什麼')),/召募、訓練、管理、運用、輔導、考核.*服務項目/);
a.match(route('志工隊不備案會怎樣').summary,/依法應備案.*不予經費補助/);
a.match(route('沒有志工服務計畫可以用志工嗎').summary,/不可以沒有計畫/);
a.match(p(route('社區發展協會的章程目的跟志願服務計畫一致，服務整年，是否還要事前備案或年底函報？')),/免於運用前申請備案.*年度結束後兩個月/);
const g=route('我們是公所自己的志工運用，不是民間協會。服務計畫已開始三個月，內容要增加送餐、隊長要換、想請補助。');
a.match(p(g),/政府機關免事前備案.*年度結束後兩個月/);
a.doesNotMatch(p(g),/運用前把服務計畫及立案登記證書/);
const long=route('立案協會受到縣府邀請，章程只有文化活動，想做兩年長者電話關懷，還沒報計畫、已經召到志工，服務要做招募、訓練、保險，想拿補助。');
a.match(p(long),/第9條.*第16條.*兩年以上.*年度結束後兩個月.*不予經費補助.*邀請函/);
const l=route('協會的志工隊長可以由沒有入會的人擔任嗎，理事會要聘他嗎？');
a.match(p(l),/未一律要求志工隊長是協會會員.*理事會或董事會聘任/);
a.match(p(l),/第11條.*指定督導/);
a.match(p(l),/沒有入會.*擔任隊長/);
a.match(p(route('不是協會自己組隊，是醫院志工隊，隊長一定要由董事會聘任嗎？')),/該醫院志工督導/);
const team=route('志工隊長一定要是會員嗎？我不知道是協會隊、祥和小隊還是公所的。');
a.equal(team.choices.length,4);
a.match(p(route(team.choices[0].question)),/志工隊長不是協會理事長/);
a.match(p(route(team.choices[1].question)),/祥和志工方案/);
a.doesNotMatch(p(route(team.choices[2].question)),/如是祥和志工方案/);
a.match(p(route('更正，問的是協會的志工隊，而不是理事長。隊員選完，理事會能直接撤掉嗎？')),/撤換權限與程序/);
const match=route('一般協會剛組志工隊，不是問要不要入會。志願服務計畫要寫哪些項目、開始前要備案嗎？');
a.equal(match.choices.length,3);
a.match(route(match.choices[0].question).summary,/符合免事前備案/);
a.match(route(match.choices[1].question).summary,/與章程目的不符/);
a.equal(route(match.choices[2].question).choices,undefined);
for(const q of ['協會志工隊的背心要買，可以用經費嗎？','隊長叫我把材料費匯到他的私人帳戶，志工隊有服務計畫怎麼辦？','志工用服務時數抵會費嗎？','社區巡守隊隊長是理事長能不能兼？','新題，竹田鄉文化團體幾個？'])a.equal(route(q),null,q);
a.match(route('志工要不要簽志願服務計畫').summary,/不一定要簽計畫本身/);
a.match(route('志工名冊要不要備查').summary,/備案的是計畫和證書影本，不是志工名冊/);
a.match(route('志工隊要不要有隊長').summary,/沒有規定志工隊一定要設隊長/);
