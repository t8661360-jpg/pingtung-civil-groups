'use strict';
const assert=require('node:assert/strict');const {route}=require('./volunteer-team-governance');
const all=x=>JSON.stringify(x);
const only=route('協會附設志工隊，要另向縣府立案嗎？');
assert.match(all(only),/不必為此另外立案/);
assert.match(all(only),/第7條第4項免事前備案/);
const full=route('我們社區發展協會下的志工隊不是獨立立案，有會員也有居民；章程已明寫送餐，前任說先把志工計畫報資料，隊長想固定收每人500放私戶，不繳就不能排班。一部分說是材料費、一部分要買志工意外險，群組對帳，縣府補助還沒核定，另外和合作社合辦。誰可以收、開什麼證明、志工服務是否要重訂計畫、年度報告什麼時候、私戶已收該如何整理、哪一邊管保險？');
for(const s of ['第7條第4項免運用前申請備案','年度結束後兩個月內','私人帳戶','非會員志工不能','實支分攤','第16條','私戶已收的先停止新增','未核定不以補助款抵付','群組報帳'])assert.ok(all(full).includes(s),s);
const unlike=route('我們協會一年做老人送餐，章程只寫體育。訪視志工不是會員，隊長要每人每月繳200到他的私人帳戶，備案、報告和會費怎麼辦？');
assert.match(all(unlike),/不適用第7條第4項/);
assert.match(all(unlike),/運用期未滿兩年者於結束後兩個月/);
const now=route('更正：只有章程這點，章程也有寫老人送餐，其他費用與帳戶情況不變。',unlike.volunteerGovernanceContext);
assert.match(all(now),/第7條第4項免運用前/);
assert.match(all(now),/非會員志工不能/);
assert.match(all(now),/私人帳戶/);
assert.doesNotMatch(all(now),/運用期未滿兩年者/);
const other=route('更正：不是協會的志工隊，是普通合作社的服務小隊；只問已正式入社的社員依章程繳的社股，小隊沒有另外收費或募款。',full.volunteerGovernanceContext);
assert.match(other.title,/社員繳社股/);assert.doesNotMatch(all(other),/第7條第4項|未核定不以補助款/);
const ask=route('隊上說要我先繳會費，跟他們拿報名表就算加入團體嗎？');
assert.equal(ask.choices.length,3);
assert.equal(new Set(ask.choices.map(o=>route(o.question,ask.volunteerGovernanceContext).title)).size,3);
for(const q of ['新題：枋寮鄉有哪些社區發展協會？','我們協會月底開會員大會，要幾天前通知？','志工服務受傷，意外事故保險怎麼理賠？','組織協會正要成立，發起人需要幾人？']) assert.equal(route(q,full.volunteerGovernanceContext),null,q);
