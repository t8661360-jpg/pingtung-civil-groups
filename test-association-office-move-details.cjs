const assert=require('node:assert/strict');
const {moveDetails:m,route}=require('./association-shared-office.js');
const contents=r=>[r.summary,...r.steps.flat()].join(' ');
const same=m('我們是屏東的協會，會址要從東港搬到潮州，章程上有寫門牌，只開理事會就可以換地址、換立案證書嗎？');
assert.match(contents(same),/所載|章程載明舊門牌/);
assert.match(contents(same),/大會|過半出席/);
assert.match(contents(same),/立案證書是否另需處理/);
const service=m('不是要搬正式會址，是要借高雄朋友的辦公室當固定服務點；我們會員還是只在屏東，那要改組織區域、改章程，還是報一個分支機構？房東口頭同意可以嗎？',same.officeMoveContext);
assert.match(service.title,/固定服務點/);assert.match(contents(service),/組織簡則.+大會.+核准/);assert.match(contents(service),/書面同意/);
const unknown=m('我們是屏東的團體，原來章程寫舊會址，租約月底到期，下個月換去別的縣市，但原縣會員照舊，舊點還要留作分會。理事長說只改通訊地址，不通知會員，也不修改章程就先到法院辦變更；我們手上有原立案證、但不確定有沒有法人登記，想知道這做法行不行、主管機關要找誰、需要什麼場所證明，以及新地址什麼時候才能拿去給銀行和補助機關？');
assert.equal(unknown.officeMoveContext.status,'unknown');assert.equal(unknown.choices.length,2);assert.match(contents(unknown),/原立案主管機關.+申請核准/);assert.match(contents(unknown),/舊址若要留作分會/);assert.match(contents(unknown),/銀行、稅籍、補助/);
const yes=m(unknown.choices[0].question,unknown.officeMoveContext);
const no=m(unknown.choices[1].question,unknown.officeMoveContext);
assert.match(contents(yes),/四分之三/);assert.match(contents(yes),/原登記法院.+移送登記簿/);assert.match(contents(yes),/換發法院法人登記證書/);
assert.match(contents(no),/這次不用去法院變更/);assert.doesNotMatch(contents(no),/四分之三|原登記法院/);
for(const r of [yes,no])assert.match(contents(r),/原立案主管機關|舊址若要留作分會/);
const corrected=m('我剛確認沒有在法院登記，而且不是外縣市了，是搬到內埔，章程也只寫設於屏東縣，不是門牌。還要跑法院或重辦成立嗎？',unknown.officeMoveContext);
assert.match(contents(corrected),/不因門牌變動而必須修章/);assert.match(contents(corrected),/不用去法院/);assert.doesNotMatch(contents(corrected),/四分之三|外縣市/);
assert.equal(m('換題，合作社修改章程是只要理事會表決嗎？',corrected.officeMoveContext),null);
assert.equal(m('我們協會只是要改開會地點，不是要搬會址，日期不變要重發通知嗎？'),null);
assert.equal(m('合作社搬社址章程地址要改，還要另找法院辦社團法人嗎？'),null);
assert.equal(m('會址想搬到外縣市，可以嗎？'),null);
assert.equal(m('櫃檯會址確認:registered'),null);
assert.match(m('協會換通訊地址，正式會址不變，需要改法院的資料嗎？').title,/只改收信地址/);
assert.match(route('協會換通訊地址，正式會址不變，需要改法院的資料嗎？').title,/只改聯絡地址/);
console.log('會址、修章、據點及法院分支均通過');
