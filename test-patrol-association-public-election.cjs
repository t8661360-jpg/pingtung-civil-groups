'use strict';
const assert=require('node:assert/strict');
const {electionAnswer}=require('./association-public-election');
const time=new Date('2026-11-27T12:40:00Z');
const base=electionAnswer('理事長可以用協會名義幫候選人站台嗎？',time);
assert.equal(base.choices.length,2);
const hub=electionAnswer(base.choices[0].question,time);
assert.match(hub.summary,/投票日不能助選/);
assert.match(hub.steps.flat().join(' '),/社群、LINE或簡訊轉發.*2026年11月28日/);
const inside=electionAnswer(base.choices[1].question,time);
assert.match(inside.summary,/協會會內選務/);
assert.doesNotMatch(JSON.stringify(inside),/2026年11月28日|D0020010/);
const day='協會理事長想在11月28日去幫地方選舉候選人站台，沒有用會費，可以嗎？';
assert.match(electionAnswer(day,time).summary,/不可以.*不用協會會費/);
assert.doesNotMatch(JSON.stringify(electionAnswer(day,new Date('2027-02-01T04:20:00Z'))),/2026年11月28日/);
const night=electionAnswer('11月27日晚上10點半用協會名義公開助選可以嗎？',time);
assert.match(night.summary,/22:00後原則上/);
assert.match(night.steps.flat().join(' '),/不妨礙居民生活或社會安寧/);
const room=electionAnswer('協會免費借場地給候選人，問選委會還是監察院？',time);
assert.match(room.summary,/政治獻金，問監察院.*問選委會/);
assert.match(room.steps.flat().join(' '),/單次活動借場地不是一概等同設競選辦事處/);
const office=electionAnswer('公職選舉候選人能把競選辦事處設於協會嗎？',time);
assert.match(office.summary,/競選辦事處不能設在依法設立的協會/);
for(const q of ['我在哪裡投票？','協會選理事要幾票才當選？','合作社理事長能不能幫候選人站台？','一般協會要向公所借場地開會員大會嗎？','公投案可以怎麼宣傳？'])assert.equal(electionAnswer(q,time),null);
console.log('public election and association election routing OK');
assert.match(electionAnswer('協會在投票日前一天晚上10點半能公開助選嗎？',time).summary,/22:00後原則上/);
assert.doesNotMatch(electionAnswer('11月27日晚上22:00整協會公開助選可以嗎？',time).summary,/22:00後原則上/);
assert.equal(electionAnswer('與助選無關：協會只搬辦公室、不用修章，會址要怎麼備查？',time),null);
