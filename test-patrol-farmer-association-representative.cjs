'use strict';
const assert=require('node:assert/strict');
const {farmerRepresentative:answer}=require('./farmer-association-representative');
const steps=a=>a.steps.flat().join(' ');
const original=answer('農會會員代表怎麼選');
assert.equal(original.choices.length,2);
const [lower,upper]=original.choices.map(x=>answer(x.question));
assert.match(steps(lower),/200人以下（含200人）.*超過200人.*無記名單記/);
assert.match(steps(upper),/下級農會.*大會選舉.*當然代表.*無記名連記.*三分之一以上/);
assert.match(answer('我們鄉農會有250名普通會員，農事小組怎麼選會員代表？贊助會員能投票嗎？').summary,/贊助會員不能投票.*250人.*分區選會員代表/);
assert.match(answer('鄉農會要選去縣農會的代表，是大家直接投還是會員代表大會選？').summary,/大會選出.*當然代表/);
assert.match(answer('區農會不含贊助會員只有200人，會員代表怎麼選？').summary,/200人，應開會員大會/);
assert.match(answer('我們基層農會有250名普通會員，會員代表怎麼選？').summary,/250人.*分區選會員代表/);
const proxy=answer('我農會入會才五個月，可以請親友幫我登記參選會員代表和代投票嗎？');
assert.match(proxy.summary,/投票日前一日仍未滿六個月.*委託登記不會補足年資/);
assert.match(steps(proxy),/公告受理之日起五日內.*本人憑國民身分證領票/);
assert.match(steps(proxy),/指導員及監票員依本人意思共同協助/);
for(const q of ['漁會會員代表怎麼選？','協會的會員代表怎麼選？','農會信用部可以請會員代表協助貸款嗎？','農會理事長由誰選？'])assert.equal(answer(q),null,q);
console.log('farmer association representative, nomination and voting tests passed');
assert.match(steps(answer('一般協會和農會的會員代表選法一樣嗎？')),/一般協會不套.*200人.*超過300人.*備查/);
