const assert=require('node:assert/strict');
const route=require('./social-worker-practice-triage').route;
const first=route('我有社工師證書，在高雄機構執業，屏東協會聘我每週去幾天，可以兩邊固定工作嗎？公會要重入嗎？');
assert.match(first.summary,/以一處為限/);
assert.match(JSON.stringify(first.steps),/公會是執業所在地/);
const b=route('更正：不是第二個固定工作，是偶爾到屏東支援個案服務。要先報准、變更原登記還是通知協會？',true);
assert.match(b.title,/支援.*報備與事先報准/);
assert.match(JSON.stringify(b.steps),/30 日.*一年.*副知受援地/);
const c=route('社工師要把主要執業處改成屏東，在新機構接案、退出舊公會，要辦哪種執照？');
assert.match(c.title,/原機關備查、新地重辦/);
assert.match(JSON.stringify(c.steps),/新單位到職日起 30 日.*舊照.*未核發/);
const d=route('我們是社區發展協會，不是社會工作師事務所，想聘一個領證但尚未辦執業的人、另一位外地社工師支援，保存個案紀錄能否交志工，能否用事務所名義收費？');
assert.match(d.summary,/不能用事務所名義收費/);
assert.match(JSON.stringify(d.steps),/至少保存 7 年.*不得無故洩漏/);
const z=route('社工師想在屏東執業，但還沒決定是首次登記、臨時支援還是搬遷，可以選嗎？');
assert.equal(z.choices.length,4);
for(const [i,p] of [/首次執業/,/短期跨縣市/,/主要執業地改到/,/先分首次登記/].entries())assert.match(route(z.choices[i].question).title,p);
assert.equal(route('更正：不是社工師，是護理師，公會要怎麼入會？',true),null);
assert.equal(route('另問：內埔鄉已解散的學術文化團體有幾個？',true),null);
assert.equal(route('社工師公會今年怎麼改選理監事？'),null);
console.log('social work: practice establishment, supported exception, inter-county change and confidentiality passed');
