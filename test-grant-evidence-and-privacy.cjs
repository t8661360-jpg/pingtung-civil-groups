'use strict';
const a=require('node:assert/strict');
const {route}=require('./grant-evidence-and-privacy');
const body=r=>r.summary+' '+r.steps.flat().join(' ');
const before='活動核銷已送出，發現照片認得出領物資的人，公開版還沒貼，能先處理遮臉、不能動原單據嗎？';
let r=route(before);
a.match(body(r),/沒有必要當作已發生公開外洩.*原版、修訂時間/);
a.doesNotMatch(body(r),/立刻停止不必要的公開分享/);
const wrong='協會領文化局核銷，原成果相簿誤貼了小朋友手持簽到表的照片，識別得出名字，兩天後才到報送期限。能整份刪去重做，還是只調公開版？';
a.match(body(route(wrong)),/停止公開.*現行第12條.*通知受影響者/);
const both='我們社區協會在東港辦共餐，兩個機關分攤費用、發票只一張、成果照片有住民，還有簽領表和服務日期。機關問我要正式備查資料，另有人要我在臉書公開，可以用相同附件嗎？';
r=route(both);
a.match(body(r),/各自核定與實際負擔分攤.*不能用同一張發票向兩機關各請同一筆/);
a.match(body(r),/不表示受助民眾名冊或原成果附件也要上網/);
a.equal(r.choices.length,2);
a.match(body(route(r.choices[0].question)),/沒有必要當作已發生公開外洩/);
a.match(body(route(r.choices[1].question)),/第12條.*通知受影響者/);
const revised='更正，公所沒有補助，只有縣府和企業捐物品；依舊要求成果，照片還沒取得允許，帳務要怎麼分不搞混？';
r=route(revised,both);
a.match(body(r),/企業實物捐贈另留/);
a.doesNotMatch(body(r),/有多個補助機關|先下架/);
const only='更正，沒有公開照片，簽到還沒做實名名單，只有一個主辦跟不同贊助者；承辦問分別有多少人，只有報送不是給社群，這時候還要先等照片同意嗎？';
a.match(body(route(only,both)),/不必另外建立實名名單或附照片/);
const plain='我的戶籍地址變更了，借用活動中心開會員大會，要怎麼通知？';
a.equal(route(plain),null);
a.equal(route('公司想申請補助，要怎麼填預算？'),null);
