const assert=require('node:assert/strict');
const {query,response}=require('./directory-count-intent.js');
const towns=['佳冬鄉','內埔鄉','萬丹鄉','屏東市'];
const cats=[['學術文化團體',/文化/],['體育運動團體',/運動|健走/]];
const ask=(q,old)=>query(q,towns,cats,old);
const q1=ask('佳冬鄉學術文化團體有幾個？只算還在運作的。');
const q2=ask('剛才佳冬改成內埔，一樣學術文化，只看存續。',q1);
assert.deepEqual(q2.regions,['內埔鄉']);assert.equal(q2.scope,'live');
const q3=ask('不是存續，改算已解散，地方和分類不變。',q2);
assert.deepEqual(q3.regions,['內埔鄉']);assert.equal(q3.scope,'gone');assert.equal(q3.filters[0].name,'學術文化團體');
const q4=ask('不要學術文化了，看全部類別，但還是只算已解散。',q3);
assert.equal(q4.filters[0].key,'all');assert.equal(q4.scope,'gone');assert.deepEqual(q4.regions,['內埔鄉']);
assert.equal(ask('另問：一般協會的會址變更，需要會員大會嗎？',q4),null);
assert.equal(ask('不是存續，改算已解散，地方和分類不變。'),null);
const a=ask('佳冬鄉有幾個登山健走團體？只算存續。');assert.equal(a.kind,'unsupported');
const b=response('',a,[],{});assert.ok(b.summary.includes('獨立統計'));assert.equal(b.choices[0].label,'查看全部體育運動團體');
assert.equal(ask(b.choices[0].question).filters[0].name,'體育運動團體');
console.log('地名更正、自然狀態接續及子分類分流通過');
const previous=ask('萬丹鄉、佳冬鄉各有幾個存續學術文化團體？');
const reduced=ask('萬丹不要，佳冬其他一樣，想知道總數',previous);
assert.deepEqual(reduced.regions,['佳冬鄉']);
assert.equal(reduced.filters[0].name,'學術文化團體');
