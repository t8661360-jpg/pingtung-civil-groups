'use strict';
const a=require('node:assert/strict');
const {route}=require('./election-staff-objection');
const before=route('協會的理事候選人同時當監票員，有人想異議，現在還沒開票，可以怎麼做？');
a.match(before.summary,/會議主席或主持人/);
a.match(before.steps.flat().join(' '),/第8條.*未明定候選人一律不得擔任/);
const after=route('協會理監事候選人兼唱票，有人說當選一定不算，結果昨天公布，我應該先向誰反映？');
a.match(after.summary,/宣布日起15日內書面向協會.*不代表當選自動無效/);
a.match(after.steps[0][1],/收件後另有15日.*向縣府反映不是/);
const coop=route('合作社的社員代表選舉，候選人自己當監票員，異議是找縣府或合作社？');
a.match(coop.steps[0][1],/第20條.*第18條第2項公告.*不得兼任/);
const [present,absent]=coop.choices.map(x=>route(x.question));
a.match(present.summary,/在現場向會議主席/);
a.match(absent.summary,/會議後3日內書面向主管機關.*郵戳/);
a.match(route('合作社以通訊投票選社員代表，候選人又兼監票，怎麼異議？').summary,/不直接套現場期限/);
const credit=route('信用合作社的社員代表選舉，候選人兼監票，異議是向誰提？');
a.match(credit.steps[1][1],/現場|當場向監選人員/);
a.doesNotMatch(credit.steps[0][1],/不得兼任/);
a.match(credit.choices.map(x=>route(x.question))[1].summary,/選舉揭曉後3日內/);
for(const s of ['選議員的候選人可兼監票員嗎？','協會候選人能當監事嗎？','農會理監事候選人監票，選舉異議誰受理？'])a.equal(route(s),null,s);
const unspecified=route('會員大會選理事，列在候選名單的人要自己監票，目前還在會議，我可以請主席先換人嗎？');
a.match(unspecified.summary,/人在現場.*記錄疑義/);
a.equal(unspecified.choices.length,3);
const types=unspecified.choices.map(x=>route(x.question));
a.match(types[0].summary,/會議主席或主持人/);
a.match(types[1].summary,/立即向會議主席/);
a.match(types[2].summary,/立即向監選人員/);
a.ok(types.every(x=>!x.choices));
const absentAssoc=route('協會理監事候選人兼監票，結果已宣布，我那天未出席，可以在15日內寫給協會嗎？');
a.match(absentAssoc.summary,/未出席不能直接套/);
a.doesNotMatch(absentAssoc.steps.flat().join(' '),/把15日內書面向協會提出/);
a.match(route('一般合作社已公告的社員代表候選人同時擔任記票，昨天會議我沒去，選舉結果有異議怎麼辦？').summary,/會議後3日內/);
