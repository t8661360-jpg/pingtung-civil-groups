const assert=require('node:assert/strict');
const {route}=require('./association-unpaid-wage-triage.js');
const answer=q=>{const a=route(q);assert(a,q);return a;};
const all=a=>[a.title,a.summary,...(a.steps||[]).flat()].join(' ');
const simple=all(answer('我們是協會受僱的總幹事，薪水兩個月沒發，理事長說等補助才給，我可以找誰？'));
assert.match(simple,/申訴與討回欠薪是兩條路/);assert.match(simple,/勞務提供地/);assert.match(simple,/勞動暨青年發展處/);
const compound=all(answer('協會聘僱出納，已到期兩個月沒付工資，要我簽已清償收據，另叫我從私人帳戶代付，協會準備解散，去哪申訴與調解？'));
assert.match(compound,/不要先簽/);assert.match(compound,/別用私人帳戶代付/);assert.match(compound,/協會解散與欠薪分開/);
const outside=all(answer('協會在屏東立案，我工作在高雄，當聘的員工欠薪找哪裡？'));
assert.match(outside,/別縣市/);assert.doesNotMatch(outside,/屏東縣政府勞動暨青年發展處/);
const double=all(answer('社區協會欠我薪水，合作社另外欠我社員股金，各找誰？'));
assert.match(double,/勞資爭議調解/);assert.match(double,/社員股金不是工資/);
const unsure=answer('每個月拿固定錢，但有時能自己找人代班；協會說只是交通費，這算志工還是員工？');
assert.equal(unsure.choices.length,3);assert.match(all(unsure),/代班是否需經同意/);
assert.match(all(answer(unsure.choices[0].question)),/申訴與調解分開/);
assert.match(all(answer(unsure.choices[2].question)),/按實際從屬性判斷/);
assert.equal(route(unsure.choices[1].question),null);
for(const q of ['協會理事長拒簽薪資，副理事長可以代簽嗎？','不是協會，是公司員工欠薪怎麼辦？','更正，我沒有受僱或固定薪資，只是監事偶爾為開會搭車，能拿車票申請交通費嗎？','新題：佳冬鄉全部存續團體幾個？','協會員工工資墊償基金如何申請？'])assert.equal(route(q),null,q);
console.log('Wage triage, mixed liabilities, and role indices passed');
