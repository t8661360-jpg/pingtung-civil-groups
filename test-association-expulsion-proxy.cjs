const a=require('node:assert/strict');
const {route}=require('./association-expulsion-proxy.js');
const flat=r=>r.steps.flat().join(' ');
const open=route('我們協會有人被除名，可以請別人代他參加大會投票嗎？');
a.equal(open.choices.length,2);
const [p,n]=open.choices.map(c=>route(c.question));
a.match(p.summary,/不能再以會員身分投票/);
a.match(n.summary,/不等於會員已被除名/);
a.match(flat(n),/每人限代理一人/);
a.match(route('協會有人已經被大會決議除名，而且除名已生效，還可以拿先前的委託書投票嗎？').summary,/以前簽的委託書也不能代投/);
const a1=route('我們協會下次要表決除名，理事長先單方面說他不能投票，其他會員可以代他出席嗎？');
a.match(a1.summary,/理事長單方面宣布/);
a.match(flat(a1),/自己的除名案.*不得代理他人表決/);
a.equal(route('協會會員不能親自到大會投票，可以寫委託書嗎？'),null);
a.equal(route('合作社社員被除名後能委託他人投票嗎？'),null);
const b=route('協會除名有爭議，還能拿委託書在大會上投票嗎？');
a.equal(b.choices,undefined);
a.match(b.summary,/先確認除名/);
console.log('expulsion timing and proxy choices passed');
