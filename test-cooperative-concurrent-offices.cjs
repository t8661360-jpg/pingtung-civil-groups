'use strict';
const assert=require('node:assert/strict');
const {route}=require('./cooperative-concurrent-offices');
const general='合作社理事主席可以同時當協會理事長嗎？';
const x=route(general);
assert.match(x.summary,/有競爭關係.*不得兼任/);
assert.equal(x.choices.length,2);
const [compete,separate]=x.choices.map(c=>route(c.question));
assert.match(compete.steps.flat().join(' '),/確有|已確認兩邊有競爭/);
assert.match(separate.summary,/競業禁止不適用.*不能直接認定可兼/);
assert.ok(x.refs.some(r=>r.source.endsWith('flno=40')));
assert.ok(!compete.choices&&!separate.choices);
assert.match(route('消費合作社理事主席要兼協會理事長，但兩邊都向同一批人賣同類商品，可以兼嗎？').summary,/競爭線索.*須先核對/);
assert.match(route('協會理事長若只是帶公益活動，不和消費合作社競爭，可以同時做合作社理事會主席嗎？').summary,/競業禁止不適用/);
const y=route('信用合作社理事主席能同時當銀行董事嗎？和當協會理事長一樣嗎？');
assert.match(y.steps[0][1],/投資關係且經中央主管機關核准.*被投資銀行/);
assert.match(y.steps[1][1],/不能.*直接套用.*也不能反推一定/);
assert.match(route('協會理事長與銀行董事，信用合作社理事主席可以同時兼任嗎？').steps[0][0],/^協會理事長/);
for(const s of ['合作社和協會辦聯合活動，理事主席可以簽約嗎？','合作社入社員是否一定要有協會理事長資格？','信用合作社理事主席兼任時，社員大會投票要怎麼辦？','協會理事長可以兼當工會理事長嗎？'])assert.equal(route(s),null,s);
