const assert=require('node:assert/strict');
const {route}=require('./guild-grant-and-budget');
const j=JSON.stringify;
const a=route('商業公會申請縣府補助一定要附會員大會紀錄？大會還沒開怎麼辦？');
assert.match(j(a),/第33條沒有明列政府補助.*依原公告或核定函.*不要把理事會紀錄當成大會紀錄/);
assert.equal(a.guildBudgetContext.known,false);
const b=route('商業同業公會想辦展覽，產業局可能補助，但也想向會員多收一筆。政府補助、增收會費和年度預算，各要給誰審？');
assert.match(j(b),/先看申請對象.*監事會或監事審核.*五月底前.*應經會員大會決議/);
const c=route('商業同業公會已收到核定函，年度沒編這案，監事沒審、理事會已同意，能不能先簽支出，年底決算再補？');
assert.match(j(c),/先報主管機關、事後提大會追認.*不只憑理事會同意就先簽新支出/);
const d=route('我們商業同業公會展覽有縣府補助，另外主辦長期是公會興辦事業、也有事業費，自己的帳還沒拆開，大會已過年度預算、補助方要核銷。哪些要另案決議、送誰、期限看哪份？');
assert.match(j(d),/20日內辦核銷.*第35條.*第38條另立會計.*目的事業主管機關備查/);
const e=route('更正，不是工商公會，是一般協會；只是年度預算，不是補助，也沒要增收會費。',d.guildBudgetContext);
assert.match(j(e),/一般協會：依人民團體法第34條.*事後提大會追認再備查/);
assert.doesNotMatch(j(e),/20日內辦核銷|興辦事業另立會計/);
const f=route('更正，這是工業同業公會，沒有任何政府補助、只有章程常年會費，不是展覽加繳，只問怎麼收和計算。',d.guildBudgetContext);
assert.match(j(f),/生產工具.*按月繳納/);
assert.doesNotMatch(j(f),/原補助機關|五月底前/);
const m=route('這筆錢需要開大會嗎？');
assert.equal(m.choices.length,4);
const mg=route(m.choices[0].question,m.guildBudgetContext);
assert.equal(mg.choices.length,3);
const mc=route(mg.choices[0].question,mg.guildBudgetContext);
assert.match(j(mc),/第33條沒有明列政府補助|第37條/);
assert.equal(route('新題：佳冬鄉文化類團體有幾個？',f.guildBudgetContext),null);
assert.equal(route('商業同業公會理事會紀錄幾天內報？'),null);
console.log('guild-grant-and-budget OK');
