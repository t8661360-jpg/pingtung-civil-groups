'use strict';
const a=require('node:assert/strict');
const {route,follow}=require('./charitable-permit-changes');
const body=r=>r.summary+' '+r.steps.flat().join(' ');
const mid='屏東協會核准公開勸募買設備，活動結束但方案還在執行，想把餘款改買不同的物資。之前有開捐款收據，還得做什麼公告或報主管機關，能先動用嗎？';
const close='不是活動結束，是同一個協會打算解散，還有核准勸募剩餘、一般無指定捐款、借用器材和員工薪資。能不能由理事投票把這些一起送給另一個協會？';
const late='更正，沒有解散，只有申請核准的勸募活動延期。餘款用途目前不變，活動最後一天還有三天，七天期限怎麼處理？';
const r=route(mid+'；更新資料：'+close);
a.equal(r.choices.length,2);
for(const p of [/不能和其他財物一起送/,/第22條.*返還捐贈人.*主管機關認定.*繳交該機關/,/理事會同意不是解散決議/,/借用.*仍屬原主.*返還/,/勞基法第28條/,/無指定捐款.*先待清債/])a.match(r.title+' '+body(r),p);
a.match(body(route(r.choices[0].question)),/已辦法院法人登記.*民法第44條/);
a.match(body(route(r.choices[1].question)),/只有立案、未辦法人登記.*第27條/);
a.ok(follow(late));
const amended=route(r.choices[0].question+'；更新資料：'+late);
a.match(body(amended),/不到7日.*不要先宣布延長.*變更事實發生7日前.*按原日期停募/);
a.doesNotMatch(body(amended),/借用器材|未清償的債務|同意後七日內/);
a.match(route('已核准的公益勸募活動還有兩天就截止，想延長期間，先報還能接著收款嗎？').title,/不可自行延長/);
a.doesNotMatch(route(mid).title,/協會解散/);
const fast=route('協會已核准公開勸募，勸募期間快到期想延長，可以嗎？');
a.doesNotMatch(body(fast),/現在不到7日/);
a.equal(route('信用合作社解散，公開勸募餘款和普通股金可以一起給另一家嗎？'),null);
