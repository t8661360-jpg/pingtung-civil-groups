const a=require('node:assert/strict');
const assets=require('./association-dissolution-subsidized-assets.js').route;
const rep=require('./coop-association-representative-eligibility.js').route;
const x=assets('協會準備基金有一部分是補助買的設備，如果解散可以分給會員還是要繳回縣府？');
a.match(x.summary,/不能直接分給會員.*一定交回縣府.*已購設備看原核定/);
a.match(x.steps.flat().join(' '),/納入團體財產證明.*第15條.*清償債務後/);
a.match(assets('設備是縣府補助買的，另有剩下的補助款。我們協會只立案沒法人登記，解散後怎麼處理？').steps.flat().join(' '),/第8點之一，剩餘補助款應繳回.*會務輔導辦法第27條/);
a.equal(assets('合作社解散，補助買的設備可不可以分給社員？'),null);
const r=rep('合作社社員代表不是社員，可以被選成理事嗎？協會團體會員派的代表也一樣嗎？');
a.equal(r.choices.length,2);
const [p,q]=r.choices.map(x=>rep(x.question));
a.match(p.steps.flat().join(' '),/不能當作具備社員身分參選.*可以投票並列為理監事候選/);
a.match(q.steps.flat().join(' '),/第49條是法人社員代表的表決.*可以投票並列為理監事候選/);
a.match(rep('會員代表大會改選時，代表能不能投票？如果不是本人的會員資格還能當理事嗎？').summary,/若是一般協會.*可依個別資格投票或參選/);
a.equal(rep('信用合作社法人社員代表可以被選為理事嗎？'),null);
const v=require('./association-address-meeting-change.js').route;
const venue=v('協會換會址，原訂會員大會日期跟議程沒變，只換會場要重發嗎？');
a.match(venue.summary,/登記會址沒變.*更正並重發/);
a.match(venue.steps.flat().join(' '),/十五日前.*補正或改期/);
const both=v('協會登記地址也要變而且只換開會會場，會員大會日期不變，通知怎麼辦？');
a.match(both.steps.flat().join(' '),/第8條.*新.*會場/);
