'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const {route}=require('./association-shared-office.js');
const joined=a=>JSON.stringify(a);
const contact=route('協會想把聯絡地址搬到同一村，正式會址不變，也沒有另租辦公室。只要通知會員嗎，縣府名冊和寄掛號的地址要不要調？');
assert.match(contact.title,/只改聯絡地址/);
assert.match(joined(contact),/通訊欄位/);
const shared=route('一般勞動合作社租了兩間辦公室，同一門牌樓上想由社區發展協會獨立登記，所有人願意同意，但合作社的租約禁止轉租。要兩個同意書嗎，誰報兩個地址，房屋用途還是水電不會分怎麼辦？');
for(const s of ['禁止轉租','一張同意書','建物用途','理事會','社員大會','各自付款證明']) assert.ok(joined(shared).includes(s),s);
assert.match(joined(shared),/D0060125/);
const g=route('未辦法院登記的一般協會和另一個合作社想共用會議室、共用電錶，但主任機關的場地補助只核給協會，合作社拿鑰匙也想登記社址。合作社當租客還是只是借用、現場用途和原場地契約、會議決議、分攤收據、水電誰可報、縣府要看什麼？');
assert.match(joined(g),/原核定只給協會，合作社不能/);assert.match(joined(g),/沒有法院法人登記/);
const cross=route('我們屏東法院登記的社團法人要遷高雄，正式會址、章程的組織區域都會改，合作社同址但不搬。章程說要會員大會決議，還有舊戶的補助用途、借用設備和承辦人寄來的掛號資料。先問哪個縣市、先修章還是填法院、舊法院是否要移資料、新地址能不能和合作社各自辦、原公文和補助款要不要先改或歸還、租金與現在使用根據要怎麼整理？');
for(const s of ['過半出席','三分之二以上','原登記簿謄本或影本','合作社沒搬','原機關','公文重起算','有權人']) assert.ok(joined(cross).includes(s),s);
const correction=route('更正：沒有法院登記，也沒有跨縣市、也不改組織區域，只是同一鄉地址換到隔壁，合作社不搬，舊公文已收了。',cross.officeAddressContext);
assert.match(correction.title,/協會換正式會址/);assert.match(joined(correction),/不辦法院主事務所變更/);
assert.doesNotMatch(joined(correction),/社員大會|三分之二以上|核定函|登記簿謄本/);
const a=route('我們要改地址，要開什麼會、去哪邊報？');
assert.equal(a.choices.length,4);
for(const p of a.choices) assert.ok(route(p.question,a.officeAddressContext)?.steps.length>0,p.label);
const x=route('我們協會要跨縣市搬會址，原主管機關和新主管機關怎麼交接？');
assert.deepEqual(x.choices.map(p=>p.label),['有法院法人登記','沒有法院法人登記']);
assert.match(joined(route(x.choices[0].question,x.officeAddressContext)),/登記簿謄本/);
assert.doesNotMatch(joined(route(x.choices[1].question,x.officeAddressContext)),/登記簿謄本/);
for(const s of ['新題：恆春鎮有哪些學術文化團體？','合作社要開社員大會，換會議室要重發通知嗎？','信用合作社要遷社址','會員聯絡地址更改要附什麼？','合作社申請補助要怎麼列應收？','新題：同一地址能有兩個團體嗎？']) assert.equal(route(s,cross.officeAddressContext),null,s);
assert.match(fs.readFileSync(__dirname+'/index.html','utf8'),/officeAddressContext=null/);
const local=route('我們社區發展協會搬到隔壁巷，還在原鄉，章程沒寫完整門牌，理事會決議就行嗎，要拿房東哪份同意？');
assert.match(local.title,/協會換正式會址/);
assert.match(joined(local),/書表及附件問承辦/);
assert.doesNotMatch(joined(local),/三分之二以上/);
const sameFloor=route('我們普通協會只租了半間房，合作社也在同層但各自出錢，建物所有人只同意原租客，有沒有轉租權，會址和社址分別怎麼報，租約可不可以一份交兩處？');
assert.match(sameFloor.title,/同一門牌/);
assert.match(joined(sameFloor),/明確書面變更/);
