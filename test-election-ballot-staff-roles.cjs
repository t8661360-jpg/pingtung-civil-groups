'use strict';
const a=require('node:assert/strict');
const {route,ordinaryDispute}=require('./election-ballot-staff-roles');
const finance=require('./association-finance-record-retention');
const render=x=>[x.title,x.summary,...x.steps.flat(),...x.refs.map(r=>r.title)].join(' ');
const before=route('我們社區發展協會還在選務準備，理事長自己也參選。他能指派自己作記票或發票嗎，程序可以怎麼安排？');
a.match(render(before),/發票在這裡指發選舉票/);
a.match(render(before),/沒有明定所有職務一定要由不同人擔任/);
a.doesNotMatch(render(before),/15日內/);
const during=route('一般協會現場開票，候選人現在負責唱票和記票，章程沒說要不要迴避；一位實際投票的會員認為不妥。要先找主席還是監事，能要求把異議記錄嗎？');
a.match(during.summary,/先找主席或主持人/);
a.match(render(during),/不是一定要先找監事/);
const after=route('工業同業公會昨天公布結果，監票員也是理事候選人；有社員代表說選票包封還沒簽。出席的會員代表現想寫異議、向誰送、保存電子資料和紙票有差嗎？');
a.match(render(after),/書面向工業同業公會提出異議.*收件後另有15日/);
a.match(render(after),/工業團體法施行細則第52條/);
a.match(render(after),/主席和監票員一同驗簽.*異地備份.*不要自行拆封/);
const mixed='商業同業公會會員大會改選時現任理事也參選，主持人叫他發票並記票；代表提出口頭異議但沒寫，結果已宣布三天。保存電子歷程可以貼群組嗎？';
const trade=route(mixed);
a.match(render(trade),/商業團體法施行細則第45條/);
a.match(render(trade),/口頭反映會重算期限/);
a.match(render(trade),/不要自行拆封.*個資貼到群組/);
a.equal(finance(mixed),null);
const original='一般協會理事候選人想同時發選票和記票，選舉怎麼安排？';
const menu=route(original);
a.equal(menu.choices.length,3);
a.match(route(menu.choices[0].question).summary,/還沒選/);
a.match(route(menu.choices[1].question).summary,/正在投票或開票/);
a.match(route(menu.choices[2].question).summary,/結果宣布之日起15日/);
a.match(route('補充，正在開票',original).summary,/正在投票或開票/);
a.match(route('協會候選人兼監票，結果已公布，我未出席。').summary,/未出席/);
a.match(route('更正，我是一般協會，還沒選、不是要異議；只想知道同一個人兼發選舉票和記票的配置問題。',original).summary,/先核對章程/);
for(const q of ['新題：九如文化類團體幾家？','協會義賣開立統一發票並保存多久？','一般合作社已公告候選人自己監票？','信用合作社候選人同時做選務？','職業公會候選人同時做選務？','協會理事候選人使用通訊投票且兼任監票？','會員大會要先知道候選人可否兼監票'])a.equal(route(q,original),null,q);
a.match(finance('協會會計憑證的原始發票開出後，決算年度已結束，應保留幾年？').summary,/至少保存十年/);
const coop='一般合作社已公告的社員代表候選人兼記票，昨天選舉我沒出席，結果有異議怎麼辦？';
a.equal(ordinaryDispute(coop),true);
a.match(require('./election-staff-objection').route(coop).summary,/會議後3日內書面向主管機關/);
a.equal(ordinaryDispute('合作社候選人公告的電話錯誤，要去哪裡異議？'),false);
a.equal(ordinaryDispute('信用合作社候選人兼記票，選舉有異議。'),false);
const html=require('node:fs').readFileSync(require('node:path').join(__dirname,'index.html'),'utf8');
a.ok(html.indexOf('const ballotStaff=')!==-1&&html.indexOf('const ballotStaff=')<html.indexOf('const financeRecords='));
a.match(html,/election-ballot-staff-roles\.js\?v=1/);
