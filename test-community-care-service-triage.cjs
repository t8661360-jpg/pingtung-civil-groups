const assert=require('node:assert/strict');
const route=require('./community-care-service-triage').route;
const a=route('我們是屏東的社區發展協會，想用活動中心辦長輩共餐跟電話問安，要先立案成長照機構，還是可以申請社區照顧關懷據點？');
assert.match(a.title,/關懷據點方案/);
assert.match(JSON.stringify(a.steps),/115 年.*至少.*3 項/);
const b=route('如果已經有社區照顧關懷據點，想加一日白天照顧、讓照服員做失能長輩的照顧、家屬付費、報長照給付，原本核定函可以直接沿用嗎？',true);
assert.match(b.summary,/不能直接沿用/);
assert.match(JSON.stringify(b.steps),/許可.*人員.*收費.*特約/);
const c=route('更正：只做共餐、關懷訪視和健康促進，不提供日間照顧；場地借村活動中心，部分食材由縣府補助、部分由長輩自費、志工要送餐、長輩聯絡名冊能不能放群組？',true);
assert.match(c.title,/只做共餐與關懷/);
assert.match(JSON.stringify(c.steps),/不能向不同補助重複核銷.*不貼公開群組/);
const d=route('我們是屏東社區協會，已有關懷據點；想新增巷弄長照站照顧失智長輩、收費、外包供餐、用共餐補助付同筆食材、公布名冊，怎麼分？',true);
assert.match(d.title,/許可和特約/);
assert.match(JSON.stringify(d.steps),/預防延緩失能.*消防.*外包供餐/);
const q='社區想設關懷據點，不確定是巷弄長照站還是日間照顧，申請可以先讓我選嗎？';
const e=route(q);assert.equal(e.choices.length,4);
for(const [i,r] of [/關懷據點方案/,/巷弄長照站：/,/日間照顧：/,/按服務內容分/].entries())assert.match(route(e.choices[i].question).title,r);
assert.equal(route('不是要辦托老，只想申請據點做共餐，到底要先確認是據點還是巷弄長照站，你可以讓我選嗎？',true).choices.length,3);
assert.equal(route('另問：內埔鄉學術文化團體有幾個存續？',true),null);
assert.equal(route('社區辦共餐後，大家疑似食品中毒與腹瀉，要怎麼處理？',true),null);
console.log('care service: annual plan, institution permit, mixed finance, private data and choices passed');
