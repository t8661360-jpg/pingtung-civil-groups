'use strict';
const assert=require('node:assert/strict');
const {doubleFactory:answer}=require('./industrial-guild-double-representation');
const body=a=>a.steps.flat().join(' ');
const direct=answer('工業同業公會的會員代表可以同時代表兩家工廠嗎？');
