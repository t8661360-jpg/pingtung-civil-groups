const assert=require('node:assert/strict');
const {route}=require('./staff-records-handover');
const j=JSON.stringify;
const own=route('我是社區發展協會的總幹事，離職後帳簿和公用存摺還在我手上，要交給誰？');
assert.match(j(own),/由協會指定接收人/);
assert.doesNotMatch(j(own),/就任後十五日內/);
const together=route('協會總幹事走了沒交帳簿，剛好也改選了，新任理事長可以先在另一家銀行開戶嗎，原補助核銷還有一張憑證沒找到怎麼辦？');
assert.match(j(together),/由協會指定接收人.*就任後十五日內.*另開新帳戶.*原核定承辦/);
const book=route('協會總幹事離開了，會裡的會計憑證和存摺得交誰，監事可以先來對嗎？');
assert.match(j(book),/監事查帳不等於可自行拿存摺/);
const generic=route('會計離職要怎麼交接');
assert.equal(generic.choices.length,2);
const c=route(generic.choices[1].question,generic.staffRecordsContext);
assert.equal(c.choices.length,3);
const online=route(c.choices[2].question,c.staffRecordsContext);
assert.match(j(online),/合作社經理或出納離職.*不要要求對方交出網銀密碼/);
const corrected=route('更正，沒改選，也不是協會，是一般合作社的經理不交帳和網銀密碼，不想跟他要密碼，怎麼處理？',together.staffRecordsContext);
assert.match(j(corrected),/合作社經理或出納離職.*原銀行.*重設存取/);
assert.doesNotMatch(j(corrected),/就任後十五日內|原核定承辦/);
const invoice=route('協會聘的會計離職不肯交回原始憑證，縣府補助核銷下週到期，可以用網銀明細先送嗎？誰追資料、找誰問能不能補件？');
assert.match(j(invoice),/不能自行當成發票或支用單據的替代品/);
const police=route('總幹事離職沒交接，帳冊在他那邊，協會可以告他嗎');
assert.match(j(police),/沒交帳簿就判定侵占/);
assert.equal(route('佳冬鄉文化類團體有幾個？',online.staffRecordsContext),null);
assert.equal(route('社團法人應該如何在銀行開戶？'),null);
assert.equal(route('銀行的員工離職要提前幾天說？'),null);
assert.equal(route('商業同業公會的會計離職，存摺怎麼交還？'),null);
console.log('staff-records-handover OK');
