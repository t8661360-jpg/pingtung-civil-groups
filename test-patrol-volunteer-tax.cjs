const assert=require('node:assert/strict');
const {answerMixed,volunteerTravelMealTax:answer}=require('./verified-mixed-questions.js');
const body=q=>JSON.stringify(answerMixed(q));
const per='協會依實際服務次數發給志工交通費和誤餐費，志工要報所得嗎？';
assert.match(body(per),/按實際服務次數及適用標準.*免納個人所得稅/);
assert.match(body(per),/09404548760/);
assert.equal(answer(per).choices,undefined);
assert.match(body('每個月固定發給志工的津貼要報稅嗎？'),/不能直接套用免稅規則/);
const org='縣府補助協會志工送餐經費，協會自己收到的款也免稅嗎？';
assert.match(body(org),/不能用志工個人的免稅函令判斷/);
assert.equal(answer(org).steps[0][0],'協會自己的收入不是志工個人所得');
const both=body('縣府補助協會的送餐款要報所得嗎？我們另外按實際服務次數發給志工誤餐費，志工要報稅嗎？');
assert.match(both,/志工的交通費或誤餐費符合條件可免納個人所得稅.*協會收到的款不因此免稅/);
const choice=answer('志工誤餐費要報稅嗎？');
assert.equal(choice.choices.length,3);
for(const c of choice.choices)assert.ok(answer(c.question),c.question);
assert.equal(answer('志工誤餐費可以補助嗎'),null);
assert.equal(answer('公司員工交通費要報稅嗎'),null);
assert.equal(answer('協會可以幫志工保意外險嗎'),null);
