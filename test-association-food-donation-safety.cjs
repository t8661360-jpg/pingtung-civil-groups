const assert=require('node:assert/strict');
const route=require('./association-food-donation-safety').route;
const ask='協會收到商家捐的常溫即期食品，沒過期，可以當天免費發給弱勢嗎？要留捐贈來源紀錄嗎？';
const a=route(ask);assert.match(a.title,/即期不等於過期/);
assert.match(a.summary,/有效日期內完成轉贈/);
assert.match(JSON.stringify(a.steps),/追溯紀錄和救助名冊分開/);
const b=route('更正：不是商家捐，是居民給了沒標日期的自製熟食，原本擺室溫，明天志工還能送嗎？',true);assert.match(b.title,/不要隔夜送/);
const c=route('假設捐贈是已包裝冷藏食品，部分過效期、部分包裝破損；要一併寄到偏鄉、發給家戶、捐贈收據怎麼辦？',true);
assert.match(c.summary,/不可以一併寄送或發放/);
assert.match(JSON.stringify(c.steps),/收據不會使不安全食品/);
const d=route('補充：我們協會是物資銀行據點，有冷藏設備但送餐時停電，部分餐食已發下去，有人反映不舒服。要怎麼辦？',true);
assert.match(d.title,/停止發放.*通知衛生局/);
for(const pattern of [/119/,/迅速|儘速就醫/,/批號/,/食品業者/,/醫療機構/,/不得把受助人姓名/])assert.match(JSON.stringify(d),pattern);
const e=route('協會要發放食品給弱勢，捐贈食品要注意什麼？');assert.equal(e.choices.length,4);
assert.match(route(e.choices[0].question).title,/即期/);
assert.match(route(e.choices[1].question).title,/冷藏或冷凍/);
assert.match(route(e.choices[2].question).title,/自製熟食/);
assert.match(route(e.choices[3].question).title,/停止發放/);
assert.match(route('協會送共餐食物給弱勢，已發下去多人不舒服疑似食品中毒。要聯絡誰？').title,/停止發放.*通知衛生局/);
assert.equal(route('另問：佳冬鄉學術文化團體有幾個存續？',true),null);
assert.equal(route('協會收到企業捐款要開收據嗎？'),null);
assert.equal(route('社區想做共餐與見面活動，要怎麼申請據點？'),null);
console.log('food donations: safe intake, cooled storage, rejection and emergency triage passed');
