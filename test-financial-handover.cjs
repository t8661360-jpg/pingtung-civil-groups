'use strict';
const assert=require('node:assert/strict');
const {route}=require('./financial-handover.js');
const full=a=>JSON.stringify(a);
const mismatch=route('協會改選後新理事會發現前任留下的帳不平，新任要負責嗎，要報縣府嗎？');
for(const s of ['不會自動承擔舊差額','就任後十五日內','第22條','原主管機關窗口','三十日內報核備'])assert.ok(full(mismatch).includes(s),s);
const big=route('一般社會團體改選，承辦催上一屆的縣府補助核銷，原收據不在、銀行和帳本差額、先前有人墊款、補助款跟自籌混了、設備還是向公所借的、圖記已收但名冊不齊、新監事尚未點交、任期交接只剩一天、會計師還沒看。新任要自掏錢嗎，哪些可以先簽收、誰查核、怎麼留證、先補件還是等全部對完？');
for(const s of ['只簽實際收到','不會自動承擔舊差額','原補助窗口','不能','借用的設備另列權屬','三十日內報核備','經有權人按規定審核','不會因換屆'])assert.ok(full(big).includes(s)||s==='不能',s);
const correction=route('更正：不是協會，是一般合作社，帳和銀行都對得上；沒補助、只有前任墊付的場租憑證不見，這時可以先認定他可以請款嗎？',big.handoverFinanceContext);
assert.match(full(correction),/帳與銀行相符/);
assert.match(full(correction),/沒有查清不先報支或還款/);
assert.doesNotMatch(full(correction),/原補助窗口|三十日內報核備|先按同一天對帳|15日內接收/);
const x=route('我們交接發現錢不對，要先簽名嗎？');
assert.equal(x.choices.length,2);
const a=route(x.choices[0].question,x.handoverFinanceContext);
const c=route(x.choices[1].question,x.handoverFinanceContext);
assert.match(full(a),/十五日內接收/);
assert.match(full(c),/合作社法第35、36、39條/);
assert.doesNotMatch(full(c),/三十日內報核備|第18條/);
const st=route('社區發展協會新理事長接任，前任交了圖記和存摺，帳簿沒交。我可以只簽這兩項，不能先簽全部交接完成對吧？');
assert.match(full(st),/只簽實際收到的項目/);
assert.match(full(st),/社區發展協會/);
for(const q of ['我們協會前理事長不交存摺及印鑑，要向銀行辦掛失嗎？','信用合作社前任交接帳目有問題，要怎麼做？','新題：萬巒鄉有哪些社區發展協會？','合作社要開社員大會，原來場地改到隔壁要發新通知嗎？']) assert.equal(route(q,big.handoverFinanceContext),null,q);
