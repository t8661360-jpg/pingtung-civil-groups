'use strict';
const assert=require('node:assert/strict');
const {route, guildAndVenue}=require('./association-address-meeting-change');
const single='我們協會只換會員大會的地點，登記地址沒有變，還要辦會址變更嗎？';
assert.match(route(single).summary,/不用辦會址異動/);
assert.match(route(single).steps.flat().join(' '),/尚未發出，直接用新會場/);
assert.match(route('協會登記會址也要搬，會員大會改期。').summary,/分開辦/);
assert.equal(route('合作社的社員代表大會只換開會地點，不改登記地址，要辦協會的會址變更嗎？'),null);
const orig='工業同業公會已經歇業，另外我們協會只換大會地點，兩件事都需要辦會址變更嗎？';
const reverse='只換協會大會場地，會址沒動；另一件是工業同業公會自己不辦了，算會址變更嗎？';
const a=guildAndVenue(orig), b=guildAndVenue(reverse);
assert.ok(a&&b);
assert.match(a.summary,/不用辦會址變更.*會員工廠停業.*公會本身/);
assert.match(a.steps[0][0],/^工業同業公會/);
assert.match(b.steps[0][0],/^協會/);
assert.match(b.steps[1][1],/第63條/);
assert.ok(!b.choices);
const [factory,guild]=a.choices.map(x=>guildAndVenue(x.question));
assert.match(factory.steps[0][1],/第14條.*第61條.*短期停業/);
assert.match(guild.steps[0][1],/第63條.*第5條/);
for(const out of [factory,guild]) assert.match(out.steps[1][0],/大會場地，不用辦會址變更/);
assert.equal(guildAndVenue(orig+'合作社也一樣嗎？'),null);
assert.equal(guildAndVenue(orig+'補助是否受影響？'),null);
assert.equal(guildAndVenue('工業同業公會的會員工廠停業兩個月，需要註銷會籍嗎？'),null);
const {factoryMembership}=require('./association-address-meeting-change');
assert.match(factoryMembership('工業同業公會的會員工廠只是暫停營業兩個月，這就要註銷會籍嗎？').summary,/不到一年，不因.*直接註銷/);
assert.match(factoryMembership('工業同業公會的會員工廠停業後，還有會籍嗎？').steps[0][1],/滿一年且不能復業.*查復後/);
assert.equal(factoryMembership('工業同業公會本身歇業，工廠的會籍如何處理？'),null);
