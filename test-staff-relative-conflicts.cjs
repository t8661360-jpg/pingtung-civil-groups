const assert=require('node:assert/strict');
const {route}=require('./staff-relative-conflicts');
const j=JSON.stringify;
const g=route('信用合作社代理總經理是理事主席的配偶，可以同時在職嗎？如果主席自己也是代理的呢？');
assert.match(j(g),/不得同時任職.*一方或雙方代理都不例外/);
const b=route('更正，剛才是信用合作社的分社經理而已，沒有兼任或代理總經理，另一半仍是理事主席。資格還需誰審？',g.staffRelativeContext);
assert.match(j(b),/僅分社經理.*第13條及第14條之一/);
assert.doesNotMatch(j(b),/不得同時任職|一方或雙方代理都不例外/);
const o=route('我們是社區協會，不是信用合作社，理事長上任後想聘自己的太太兼任會計、只是每週半天，理事會同意可以嗎？');
assert.match(j(o),/不得聘僱現任理事長的配偶.*只聘半天.*不是理事長在理事會迴避表決/);
const existing=route('補充，我們其實是社區發展協會，不是合作社。理事長上任前太太已經是總幹事，現在可以續留嗎？',g.staffRelativeContext);
assert.match(j(existing),/接任前已聘僱者例外.*最初聘用日/);
const credit=route('信用合作社經理也同樣可以嗎？',existing.staffRelativeContext);
assert.equal(credit.choices.length,3);
const v=route('一般合作社的監事原本也做事務員，現在想兼著當。其他人說理事兼職有主管機關同意就可以，這個例外能用在監事嗎？能由同一位監事查自己業務嗎？');
assert.match(j(v),/監事不得兼任理事、事務員或技術員.*不能援用理事的例外/);
const mix=route('一般合作社主席跟經理是夫妻，後來經理也被選成理事，現還在領薪；薪資決議是主席簽，另有公款補助報薪，監事現在才知道，這幾件事要怎麼分開處理？');
assert.match(j(mix),/理事會公開考選.*經主管機關同意的例外.*薪資不能由本人申報後自己放行.*薪資是否可報補助/);
const industrial=route('工業同業公會秘書長想讓自己的配偶新任兼職會務，可以嗎？');
assert.match(j(industrial),/第7條第6款.*配偶或三親等/);
const q=route('理事會決議要聘理事長的兒子當幹事，理事長要迴避嗎');
assert.equal(q.choices.length,4);
const pick=route(q.choices[2].question,q.staffRelativeContext);
assert.equal(pick.choices.length,3);
assert.match(j(route(pick.choices[0].question,pick.staffRelativeContext)),/一方或雙方代理都不例外/);
assert.equal(route('新題：佳冬鄉文化類團體有幾個？',mix.staffRelativeContext),null);
assert.equal(route('理事長的兒子可以當監事嗎'),null);
assert.equal(route('協會會員可以委託配偶出席大會嗎？'),null);
console.log('staff-relative-conflicts OK');
