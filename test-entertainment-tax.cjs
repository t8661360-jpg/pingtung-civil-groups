const assert=require('node:assert/strict');
const {route:r}=require('./entertainment-tax.js');
const text=x=>[x.title,x.summary,...x.steps.flat()].join(' ');
let x=r('屏東的協會辦免費演唱活動，大家不用買票只有自由樂捐，要申報娛樂稅嗎？');
for(const p of [/115年5月22日/,/不用為這場表演辦理娛樂稅登記或申請免徵/,/公益捐助另外判斷/])assert.match(text(x),p);
x=r('更正，是協會用售票平台賣公益音樂會門票，門票收入全給慈善團體。還是要申報娛樂稅？能先賣票再申請免稅嗎？',x.entertainmentTaxContext);
assert.match(text(x),/售票或免費/);assert.match(text(x),/不把付費者的票券或材料費改開成捐款收據/);
x=r('我們不知道活動是純戶外市集還是有附表演票，也不知道票款誰代收。小屏可以先分情形告訴我找國稅局還是地方稅務局嗎？');
assert.equal(x.choices.length,4);
const c=x.choices.map(o=>r(o.question,x.entertainmentTaxContext));
assert.match(c[0].title,/不課娛樂稅/);assert.match(c[1].title,/另有收費娛樂設施/);assert.match(c[2].title,/只有市集/);assert.match(c[3].title,/舊活動/);
assert.match(r('不是協會辦表演，是合作社租場地賣自己的農產，現場沒有售票表演。還要收娛樂稅嗎？').title,/市集或賣農產/);
assert.match(r('電影售票於2026/05/21，娛樂稅怎麼辦？').title,/舊活動/);
assert.match(r('電影售票於2026/05/22，娛樂稅怎麼辦？',c[3].entertainmentTaxContext).title,/不課娛樂稅/);
assert.match(r('音樂會現場另有付費的夾娃娃機，娛樂稅怎麼拆開？').title,/另有收費娛樂設施/);
assert.match(r('音樂會只有門票，沒有KTV，娛樂稅怎麼辦？').title,/不課娛樂稅/);
assert.equal(r('合作社社員大會通知幾日前發？',x.entertainmentTaxContext),null);
assert.equal(r('協會補助活動可以核銷材料費嗎？',x.entertainmentTaxContext),null);
assert.equal(r('櫃檯娛樂稅確認:arts'),null);
console.log('Entertainment tax start date, actual scope and separate receipt routes all pass');
