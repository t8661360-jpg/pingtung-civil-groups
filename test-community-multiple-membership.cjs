'use strict';
const assert=require('node:assert/strict');
const {route,follow}=require('./community-multiple-membership');
const check=(q,...rs)=>{const a=route(q);assert(a,q);const s=[a.title,a.summary,...a.steps.flat()].join('\n');for(const r of rs)assert.match(s,r,q);return a;};
check('社區發展協會的理事可以同時是另一個社區發展協會的會員嗎',/原則可以同時/,/不會光因這點就應辭/);
check('屏東社區發展協會的理事戶籍還在原社區，但也想加鄰近的社區協會當一般會員，可以雙邊入會嗎，原本理事要辭嗎？',/分別符合兩會章程與法令/,/原理事解任/);
check('我搬家後戶籍遷出第一個屏東社區，但還在那邊做志工和當理事；新社區要我入會，原社區會籍要保留、理事能繼續、可以兩邊同時投票嗎？',/志工.*不等同持有會籍或表決權/,/確認喪失原會員或代表資格/,/不等於處罰除名/);
check('兩個協會不是同一種：A是社區發展協會，B是全縣立案的文化協會，一邊戶籍、一邊用工作地點申請，我想兼兩邊理事、兩邊投票；章程不同要怎麼看，是否一律違法？',/同時當兩會理事仍須各自具有資格/,/發起人設籍或工作.*不等同/,/分別在自己的會內行使選舉權/);
const q='屏東兩個社區組織範圍重疊，一個稱住址在其中就好、另一個說要有戶籍；我是團體代表，不是個人會員，在甲已當理事，現準備加入乙。要先確認哪份章程、戶籍跟團體地點哪個算、能任理事、能投票、搬走後如何登記異動？';
check(q,/團體本身依各會章程/,/不由新代表直接接任理事/);
const f='補充：是個人會員，戶籍確實遷出甲社區範圍，甲章程要求設籍，乙是新戶籍地；不是掛在甲團體會員的名下。';
assert(follow(f));check(q+'；'+f,/先由甲確認戶籍異動/,/乙不會因此自動有投票權/);
const miss=check('兩個社區發展協會都找我當會員，可以都投票加上當理事嗎？',/分別符合兩會章程/);
assert.equal(miss.choices.length,3);
check(miss.choices[1].question,/合法推派自然人代表/);
check(miss.choices[2].question,/不當成一般有票會員/);
check('換一題：鄰縣的協會名稱跟我的一模一樣，屏東可以立案嗎，跟社區一地只能一協會有關嗎？',/同一組織區域/,/不保證核准/,/先向公所核對組織範圍/);
for(const n of ['社區發展協會章程範本下載','合作社和協會共用地址如何變更','協會理事缺額如何補選？','人民團體法第7條全文','同一協會的團體會員代表又是個人會員，有幾票？'])assert.equal(route(n),null,n);
