const assert=require('node:assert/strict');
const {route}=require('./association-rescheduled-notice.js');
const get=(q,p)=>{const a=route(q,p);assert(a,q);return a;};
const all=a=>[a.title,a.summary,...(a.steps||[]).flat()].join(' ');
assert.match(all(get('協會的臨時會員大會改到下週，原通知有寄，到時還要重發開會通知並重新算十五天嗎？')),/原通知.*不宜當成新一場/);
const shifted=all(get('原訂12月20日的會員大會沒有召開不是流會，改到12月27日、換地址、加修章議程、會員申請未審，兩張舊委託可沿用？縣府已收列席函。'));
assert.match(shifted,/12月27日.*12月12日/);assert.match(shifted,/大會改期與主管機關列席/);assert.match(shifted,/不把待審申請者先算進去/);assert.match(shifted,/舊的委託書/);assert.match(shifted,/修章議案/);
assert.match(all(get('我們要開的是監事會，不是會員大會，時間先訂12月27日。七天通知從哪天算？')),/監事會原則在開會7日.*12月20日/);
assert.match(all(get('更正，不是會員大會，是一般協會理事會，非緊急事故，改到12月27日，也沒有委託書。最晚何時通知？')),/理事會原則在開會7日.*12月20日/);
assert.match(all(get('我們取消原訂會員大會，沒有開場、也沒有流會，現在改同天晚上用視訊，會員名冊還需要再確認嗎？')),/要看章程與議程/);
const unknown=get('我們開會改到12月27日，但是不知道是理事會或會員大會，通知最晚哪天？');
assert.equal(unknown.choices.length,4);
assert.equal(new Set(unknown.choices.map(x=>get(x.question).title)).size,4);
assert.match(get(unknown.choices[1].question).summary,/12月20日/);
const follow=get('一般協會理事會延期，通知要重發嗎？');assert(follow.noticeContext);
assert.match(get('12月27日',follow.noticeContext).summary,/12月20日/);
assert.match(get('協會明年要開會員大會，確定12月27日開，通知最晚何時到？').summary,/明年12月27日/);
for(const q of ['合作社同樣12月27日開社員大會，什麼時候寫書面通知？','更正不是改期，是會員大會出席人數不足，主席已宣布流會','新題：佳冬鄉全部存續團體幾個？','協會臨時會員大會是誰可以召集？'])assert.equal(route(q,follow.noticeContext),null,q);
console.log('Rescheduled meeting dates, agenda, participants, emergency, and choice context passed');
