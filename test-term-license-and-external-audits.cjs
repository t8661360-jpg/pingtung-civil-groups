'use strict';
const assert=require('node:assert/strict');
const {route:term}=require('./association-records-and-term');
const {licenseAndRejection:license}=require('./land-agent-guild-practice');
const {route:audit}=require('./association-external-audits');
const pure=term('新成立的協會第一屆理監事任期從哪一天起算，是成立大會還是立案那天？');
assert.match(pure.summary,/不是用立案日.*第一次理事會實際召開日/);
assert.equal(pure.steps.length,2);
const mix=term('協會成立大會和第一次理事會不是同一天，第一屆理監事任期用哪天？立案又要送哪些紀錄？');
assert.match(mix.summary,/立案送件的30日則是從成立大會後起算/);
assert.match(mix.steps[1][1],/章程、會員名冊及選任職員簡歷冊.*第一次會員大會.*第一次理事、監事會議紀錄/);
assert.equal(term('合作社新成立，第一屆理監事任期什麼時候起算？'),null);
assert.equal(term('國際性社會團體第一屆理監事任期從哪天開始？'),null);
const l=license('地政士公會可以拒絕我入會嗎？開業執照要去哪裡申請？');
assert.match(l.steps[0][1],/人民團體主管機關.*認定後才視同已入會/);
assert.match(l.steps[1][1],/事務所所在地.*屏東縣政府地政處.*開業執照不是公會發的/);
assert.match(license('地政士的開業執照去哪裡申請？公會可以拒絕我入會嗎？').steps[0][0],/^開業執照/);
assert.equal(license('地政士公會可以拒絕掛名會員嗎？如何換發開業執照？'),null);
const tax=audit('協會被國稅局查帳怎麼辦？如果是縣府查我的補助款又要準備什麼？');
assert.match(tax.steps[0][1],/通知的年度、稅目、指定資料和期限/);
assert.match(tax.steps[1][1],/核准補助文件、領款收據、實際支用明細及各項支用單據/);
assert.match(audit('協會被縣政府查補助，要附什麼資料？如果是國稅局來查帳又怎麼辦？').steps[0][0],/^屏東縣府/);
assert.equal(audit('協會的監事或理事會可以查帳嗎？'),null);
assert.equal(audit('協會被國稅局查帳會罰多少？縣府補助怎麼申請？'),null);
assert.equal(audit('協會被國稅局查帳怎麼辦？縣府補助怎麼申請？'),null);
