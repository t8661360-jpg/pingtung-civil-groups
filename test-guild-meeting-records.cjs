const assert=require('node:assert/strict');
const {route}=require('./guild-meeting-records');
const j=JSON.stringify;
const a=route('我們是屏東的公會，會員大會開完，紀錄幾天內報、要給誰？是送縣府或中央？');
assert.equal(a.choices.length,3);
const b=route(a.choices[1].question,a.guildRecordsContext);
assert.match(j(b),/七日內（7 日）.*分送各會員.*目的事業主管機關.*特定地區.*內政部/);
assert.doesNotMatch(j(b),/十五日內（15 日）/);
const com=route('我們是縣級商業同業公會，不是一般協會。這次會員大會沒改選，開會通知哪天前送、會員代表名冊要不要先報、紀錄開完幾天分送，報縣府還是目的事業主管機關？');
assert.match(j(com),/開會十五日前通知.*得報請.*大會二十日前.*逾期不聲明視為續派.*大會十五日前.*十五日內（15 日）.*縣政府/);
const ind=route('我們是工業同業公會，不是商業公會，開大會要不要附議程請派員、會後幾天把紀錄送給會員和兩個主管機關、當天另外開理事會的紀錄也一樣嗎、只有一般會議沒改選會不同嗎？');
assert.match(j(ind),/應分別報請.*沒有選舉.*七日內（7 日）/);
assert.doesNotMatch(j(ind),/商業同業公會/);
const mixed=route('我們是縣級商業同業公會，要改章程、會後大會與監事會紀錄怎麼送？如果是工業同業公會也一樣嗎？');
assert.match(j(mixed),/十五日內（15 日）.*七日內（7 日）/);
const fixed=route('補充，不是商業，是工業同業公會，這次沒有改章程，現在只問理事會跟監事會紀錄。',mixed.guildRecordsContext);
assert.match(j(fixed),/七日內（7 日）/);
assert.doesNotMatch(j(fixed),/送紀錄不等於完成修章|十五日內（15 日）/);
const n=route('護理師公會開理事會會議紀錄也像工業公會七天內寄出嗎？');
assert.match(j(n),/護理人員公會先看護理人員法及章程.*留存供會員查閱/);
const emergency=route('商業同業公會三天後要緊急開臨時會員大會，通知能不能不用提前15天？會議紀錄也能晚點才寄嗎？');
assert.match(j(emergency),/通知實際送達且能適時到會.*不延後會後紀錄期限/);
assert.equal(route('只有說我們是公會，監事會紀錄要送嗎？',com.guildRecordsContext).choices.length,3);
assert.equal(route('新題：我們是職業團體，有辦一般會員大會，要先報紀錄嗎？',com.guildRecordsContext).choices.length,3);
assert.equal(route('佳冬鄉文化類團體有幾個？',b.guildRecordsContext),null);
assert.equal(route('一般協會理事會開會紀錄幾天內報？'),null);
assert.equal(route('商業同業公會會員代表可不可以委託？'),null);
assert.equal(route('商業公會和合作社一起開會，出席怎麼算？'),null);
console.log('guild-meeting-records OK');
