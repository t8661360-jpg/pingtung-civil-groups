'use strict';
const assert=require('node:assert/strict');
const {politicalDonation:answer,legacyPoliticalDonation}=require('./association-political-donation');
const base=answer('協會可以接受政治獻金嗎？');
assert.equal(base.choices.length,3);
assert.match(base.summary,/依據是政治獻金法第5條/);
const [funds,surplus,person]=base.choices.map(x=>answer(x.question));
assert.match(funds.summary,/不要直接交付協會/);
assert.match(surplus.summary,/依法形成的賸餘政治獻金，可有條件/);
assert.match(surplus.steps.flat().join(' '),/200萬元.*超過10萬元.*原專戶.*三個月內.*四年/);
assert.match(person.summary,/不會只因身分就變成政治獻金/);
assert.match(answer('候選人可以把競選捐款直接交給協會辦活動嗎？').summary,/未確認前先不要收款或開據/);
assert.match(answer('候選人沒登記，剩餘政治獻金可以給協會做公益嗎？').summary,/申報繳庫/);
assert.match(answer('還沒投票，候選人能拿政治獻金專戶的剩餘款捐給協會嗎？').summary,/用途限制/);
assert.match(answer('選後有賸餘政治獻金，想捐給公益團體，可以捐超過10萬嗎？').summary,/有條件捐作公益/);
assert.equal(legacyPoliticalDonation('協會怎麼立案',{title:'別的答案'}),null);
assert.match(legacyPoliticalDonation('可不可以接受政治獻金？',{title:'協會不得接受政治獻金'}).summary,/第5條/);
for(const q of ['捐款要用老闆還是公司的名字開收據？','協會可以捐政治獻金給候選人嗎？','協會可以用會費幫候選人站台嗎？','候選人在哪裡登記政治獻金專戶？','合作社可收政治獻金嗎？'])assert.equal(answer(q),null,q);
console.log('political donations, campaign balance and ordinary charitable donations are separated');
assert.match(answer('這次沒有參選的前議員用自己的錢捐給協會做公益，算政治獻金嗎？').summary,/不一定/);
assert.match(answer('我們協會可不可以收政治獻金？對方沒依法登記為候選人，說選後剩的可以捐公益。').summary,/依第21條申報繳庫/);
